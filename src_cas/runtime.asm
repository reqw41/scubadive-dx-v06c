; РАНТАЙМ СТУПЕНИ 1 — универсальный загрузчик турбо-блоков.
; Ступень 1 (её грузит штатное ПЗУ в 0xDB00) переносит этот код в 0x7600
; и передаёт сюда управление. Дальше лента читается ТОЛЬКО этим кодом.
;
; Почему 0x7600: образ игры занимает 0x0100-0x75A4, видеопамять начинается
; с 0x8000. Щель 0x75A5-0x7FFF — единственное место, где загрузчик не мешает
; ни игре, ни картинке. Стек — вниз от 0x8000.
;
; ФОРМАТ ТУРБО-БЛОКА (см. tools/cas/tape.py):
;   пилот 0xFF..., 0xE6, adr_lo, adr_hi, страниц, флаги, данные, кс1, кс2
;   флаги бит0 = после загрузки прыгнуть на adr
;   кс — Флетчер-16 по данным: s1 += b; s2 += s1
;
; ФИЗИКА: уровень на входе (порт 0x01, бит 4) переключается на каждом
; импульсе, длина импульса = бит. Порог THRESH разделяет короткий (бит 0,
; 2 сэмпла ≈136 тактов) и длинный (бит 1, 5 сэмплов ≈340 тактов).
; Виток счётчика = in(12)+cp(4)+jp(12)+inc(8) = 36 тактов, поэтому
; короткий даёт ~3 витка, длинный ~9. Порог 6 стоит ровно посередине.
;
; ВСЯ побайтовая работа (запись, контрольная сумма, кайма) делается ПОСЛЕ
; возврата из rdbyte, то есть внутри СИНХРОИМПУЛЬСА следующего байта —
; окно 340 тактов, работы на ~150. Длительность синхроимпульса
; отбрасывается, поэтому опоздать внутри него безопасно.

THRESH	equ 6
MARKTH	equ 18		; метка (20 сэмплов) даёт ~36 витков, длинный бит ~9
TAPEP	equ 0x01		; порт C ППА1: бит 4 — вход с магнитофона
BORDER	equ 0x02		; кайма (она же индекс слота палитры)

	org 0x7600

	jp start		; 0x7600 — вход из ступени 1
	jp loadblk		; 0x7603 — «загрузить блок», для рантайма-2
	dw bmask		; 0x7606 — адрес маски каймы (см. ниже)

; --- загрузить блок и, если велено, прыгнуть на него ----------------------
start:
	di
	ld sp, 0x8000
	ld a, 0x88		; ППА: порт B ВЫХОД (кайма). 0x8A даёт mode512
	out (0x00), a
	in a, (TAPEP)
	ld d, a			; исходный уровень ленты
loop1:
	call loadblk
	ld a, (flags)
	rra
	jp nc, loop1		; блок без флага «пуск» — читаем следующий
; --- ЗАПУСК ---------------------------------------------------------------
; ПРЫГНУТЬ ПРЯМО НА 0x0100 НЕЛЬЗЯ: штатное двухкилобайтное ПЗУ ещё висит поверх
; 0x0000-0x07FF, и такой прыжок попадает в ПЗУ, а не в игру. Проверено прогоном
; (tools/cas/run_tape.js): на 52.9 с управление уходило в ПЗУ, оно чистило ОЗУ,
; и загруженный образ пропадал. Поэтому делаем как loadfm и кассета King's
; Valley: кладём по 0x0000 команду jp <адрес> — это точка входа после БЛК+СБР —
; и пробуем стартовать сами. На машинах с ПЗУ «Старт-1200» запись в порты уже
; сняла ПЗУ, и чтение 0x0000 вернёт наш байт; на штатном ПЗУ вернётся ПЗУ-шный,
; и тогда запуск остаётся за человеком: БЛК+СБР.
	ld hl, (dest0)
	ld a, 0xC3
	ld (0x0000), a
	ld (0x0001), hl
	ld a, (0x0000)
	cp 0xC3
	jp z, 0x0000
	xor a
	out (BORDER), a		; кайма чёрная: лента прочитана, ждём БЛК+СБР
hold:
	jp hold

; --- загрузка одного блока ------------------------------------------------
; выход: блок записан по своему адресу, (flags)/(dest0) заполнены
; портит: A,B,C,E,H,L; D — состояние входа (сквозное)
loadblk:
	xor a
	out (BORDER), a
wsync:
; Ищем МЕТКУ РАСКАДРОВКИ — импульс длиннее любого битового. Без неё
; загрузчик не знает, где граница байта: он считает импульсы девятками,
; и сдвиг даже на один импульс превращает поток в мусор.
	ld b, 0
mklp:
	inc b
	in a, (TAPEP)
	cp d
	jp z, mklp
	ld d, a
	ld a, MARKTH
	cp b
	jp nc, wsync		; импульс короткий — это ещё не метка
	call rdbyte
	cp 0xE6
	jp nz, wsync		; метка ложная — ищем снова
	call rdbyte
	ld l, a
	call rdbyte
	ld h, a
	ld (dest0), hl		; адрес назначения
	call rdbyte
	ld c, a			; сколько страниц по 256 Б
	call rdbyte
	ld (flags), a
	xor a
	ld (s1), a
	ld (s2), a
data:
	call rdbyte
	ld (hl), a
	inc hl
	ld b, a
	ld a, (s1)
	add a, b
	ld (s1), a
	ld b, a
	ld a, (s2)
	add a, b
	ld (s2), a
	ld a, l
; МАСКА КАЙМЫ — самомодифицируемый операнд, его адрес отдан наружу словом по
; 0x7606. Рантайм 2 гасит кайму (маска 0) на время НАЛИВА ЗАСТАВКИ: там прогресс
; показывает сама картинка, а полосы поверх неё — мельтешение 83 Гц. Перед
; образом игры маска возвращается в 0x0F, и кайма снова полосатит, как на ZX.
	db 0xE6			; and #
bmask:	db 0x0F
	out (BORDER), a
	ld a, l
	or a
	jp nz, data
	dec c
	jp nz, data
; --- сверка контрольной суммы --------------------------------------------
	call rdbyte
	ld b, a
	ld a, (s1)
	cp b
	jp nz, bad
	call rdbyte
	ld b, a
	ld a, (s2)
	cp b
	jp nz, bad
	xor a
	out (BORDER), a
	ret
bad:
	ld a, 0x04		; кайма красная: контрольная сумма не сошлась,
	out (BORDER), a		; перемотай ленту на начало блока и пусти снова
	jp wsync

; --- чтение байта с ленты -------------------------------------------------
; вход:  D = прошлое значение порта TAPEP
; выход: A = байт; D обновлён; портит B,E
rdbyte:
	ld b, 0
sync:
	inc b
	in a, (TAPEP)
	cp d
	jp z, sync		; ИЗМЕРЯЕМ синхроимпульс и выбрасываем результат:
	ld d, a			; его длина не значит ничего, значит только то,
	ld e, 1			; что после него начинается бит 0.
rbit:
	ld b, 0
redge:
	inc b
	in a, (TAPEP)
	cp d
	jp z, redge		; считаем витки до следующего фронта
	ld d, a
	ld a, THRESH
	cp b			; CY, если THRESH < B, то есть импульс длинный
	ld a, e
	adc a, a
	ld e, a
	jp nc, rbit
	ret			; A = собранный байт

dest0:	dw 0
flags:	db 0
s1:	db 0
s2:	db 0
