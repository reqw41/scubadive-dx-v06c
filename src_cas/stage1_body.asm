; СТУПЕНЬ 1 — единственное, что читает ШТАТНОЕ ПЗУ «boots» (F1 при сбросе).
; Формат v06c-rom, две страницы: 0xDB00-0xDCFF.
;
; ТРИ ЖЁСТКИХ ТРЕБОВАНИЯ ПЗУ К ЭТИМ ДВУМ СТРАНИЦАМ (иначе не заработает):
;
; 1) АВТОСТАРТА У ПЗУ НЕТ. Штатно после загрузки оно уходит в 0x00B5 мигать
;    светодиодом и ждать, пока человек нажмёт БЛК+СБР. Адрес возврата 0x00B5
;    положен в стек при SP=0xDCF0, то есть лежит по 0xDCEE-0xDCEF — ВНУТРИ
;    страницы 0xDC, которую мы грузим. Кладём туда слово 0xDB00, и штатный
;    ret приземляется на нас. Ковёр из этого слова до 0xDCFF — страховка от
;    смещения стека. Приём взят у загрузчика loadfm (ivagor).
;
; 2) ПЗУ РИСУЕТ КАРТУ ПРОГРЕССА ПРЯМО В ЭТИ СТРАНИЦЫ. Клетка страницы N
;    лежит по 0xC018 + (N%32)*0x100 + (N/32)*0x18: для 0xDB это
;    0xDBA8-0xDBAF, для 0xDC — 0xDCA8-0xDCAF. Туда пишутся байты 0x7E уже
;    ПОСЛЕ приёма страницы, так что держать там код нельзя — только мусор.
;
; 3) ПРОВЕРКА «страница принята» сканирует клетки и останавливается на
;    байте 0x81. Он обязан лежать сразу за восемью клетками, иначе скан
;    уедет по чужим данным и загрузка не завершится.
;
; Полезного места остаётся: 0xDB00-0xDBA7 (168 Б) и 0xDBB2-0xDCA7 (246 Б).
; Во втором куске лежит рантайм, собранный на 0x7600 (src/cas/runtime.asm);
; код в первом куске просто переносит его туда и передаёт управление.

RTDEST	equ 0x7600
RTSIZE	equ 246

	org 0xDA00

; СТРАНИЦА-ЖЕРТВА. ПЗУ просыпается не мгновенно: замерено, что первый
; подблок первой страницы оно стабильно пропускает (ловит заголовок и
; уходит уже на второй подблок). Отдаём под этот промах отдельную страницу
; мусора — так реальный код всегда попадает в уже синхронизованное ПЗУ.
	ds 0xDAA8-$, 0xFF
	ds 8, 0xFF		; клетки карты прогресса страницы 0xDA
	db 0x81, 0x81		; терминатор скана карты
	ds 0xDB00-$, 0xFF

entry:
	di
	ld sp, 0x8000
	ld hl, rtsrc
	ld de, RTDEST
	ld bc, RTSIZE
copy:
	ld a, (hl)
	ld (de), a
	inc hl
	inc de
	dec bc
	ld a, b
	or c
	jp nz, copy
	jp RTDEST

	ds 0xDBA8-$, 0xFF
	; Страница 0xDB — НЕ последняя, ей можно объявиться готовой пораньше:
	; ПЗУ увидит «страница принята» уже на подблоке 0xA0, но так как
	; страниц две (d=2), оно всё равно дочитает подблоки 0xC0 и 0xE0.
	ds 8, 0xFF		; клетки карты прогресса страницы 0xDB
	db 0x81, 0x81		; терминатор скана карты

rtsrc:				; 0xDBB2 — рантайм, собранный на 0x7600
	; Какой именно рантайм тут лежит, решает сборщик: он кладёт нужный
	; в runtime_embed.bin ПЕРЕД вызовом ассемблера. Условной сборкой это
	; делать нельзя — sjasm 0.39j молча игнорирует IFDEF и всегда собирал
	; одну и ту же ветку (поймано тем, что «штатная» лента приезжала с
	; турбо-загрузчиком внутри).
	incbin "../build/cas/runtime_embed.bin"	; у нас src_cas/ лежит в корне, а не в src/cas/
	ds 0xDCA8-$, 0xFF

	; Страница 0xDC — ПОСЛЕДНЯЯ, и вот тут вся тонкость. Подблок 0xA0
	; накрывает своими данными сразу все восемь клеток карты. Если
	; написать в них 0xFF, ПЗУ решит «страница принята» на пятом из восьми
	; подблоков, увидит d==1 и сделает ret ДО того, как приедет подблок
	; 0xE0 с адресом возврата. Поэтому клетки 6 и 7 оставляем НУЛЯМИ:
	; страница станет полной ровно тогда, когда ПЗУ пометит их само,
	; приняв подблоки 0xC0 и 0xE0. Ковёр к этому моменту уже на месте.
	ds 6, 0xFF		; клетки 0..5 — «принято»
	db 0x00, 0x00		; клетки 6,7 — пометит само ПЗУ
	db 0x81, 0x81		; терминатор скана карты
	ds 0xDCEA-$, 0xFF

	; ХВОСТ СТЕКА ПЗУ. В момент приёма этого подблока ПЗУ держит на стеке
	; (SP=0xDCEA) три слова, и мы пишем прямо поверх них — значит обязаны
	; подставить осмысленные значения, иначе ПЗУ уйдёт не туда:
	;   0xDCEA  сохранённый BC — его достанут как «страница/смещение» и
	;           проверят готовность этой страницы. Ставим 0xDB00:
	;           страница 0xDB уже полна, проверка пройдёт.
	;   0xDCEC  сохранённый DE — D станет счётчиком оставшихся страниц,
	;           а выход из цикла — ровно по D==1. Ставим 0x0101.
	;   0xDCEE  адрес возврата (штатно 0x00B5 — «мигать и ждать БЛК+СБР»).
	;           Подменяем на себя: это и есть автостарт, своего у ПЗУ нет.
	dw 0xDB00		; 0xDCEA -> BC
	dw 0x0101		; 0xDCEC -> DE
	dw entry		; 0xDCEE -> адрес возврата

	; Трамплины ПЗУ восстанавливаем дословно: если какой-то подблок не
	; примется с первого раза, ПЗУ пойдёт читать снова через них.
	db 0x00			; 0xDCF0 — дно стека ПЗУ
	db 0xC3			; 0xDCF1: jp 0x0448 — «прочитать байт с ленты»
	dw 0x0448
	db 0xC3			; 0xDCF4: jp 0x0397 — «начать ленту сначала»
	dw 0x0397
	ds 0xDD00-$, 0xFF
