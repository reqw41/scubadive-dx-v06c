// ТЕЛЕПОРТ ДАЙВЕРА В ЗАДАННОЕ ЗНАКОМЕСТО.
//
// ГДЕ ОН НА ЭКРАНЕ. Сам код отрисовки (scubacodc.asm, LE21A) берёт столбец из
// DiverObj+$00, строку из DiverObj+$19 и зовёт GetScrAddrF; спрайт занимает
// 3x3 знакоместа (dv_rows = 3). Проверено замером: жёлтые пиксели (биты в
// 0xC000 без битов в 0xE000) стоят ровно в этом квадрате.
//
// ПОЧЕМУ НЕ ПРОСТО ЗАПИСЬ. Поля ведёт движок: записали только +$00/+$19 — строка
// на следующем кадре возвращается назад (её пересчитывают из +$01). Записали и
// +$01 — строка встаёт не туда: связь +$01 -> +$19 не тождественная (при
// неподвижном окне разница выходила 3, а после переезда окна — 10).
// Разбирать её целиком незачем: связь монотонная, поэтому наводимся итерациями —
// правим +$01 на разницу и даём кадр, пока +$19 не совпадёт с целью.
//
// ⚠ ПОКА НЕ РАБОТАЕТ, И ВОТ ГРАНИЦА. Поля встают в цель (+$19 и +$00 совпадают с
// заданными), но дайвер В НОВОЙ КЛЕТКЕ НЕ РИСУЕТСЯ: жёлтых байт там ноль и через
// 5, и через 25 кадров. Значит +$19/+$01 — не источник истины, движок держит
// положение ещё где-то (кандидаты: +$13/+$14 — точные X/Y, +$11/+$12) и
// перерисовку заводит от них.
// Ещё ловушка на будущее: «самый жёлтый квадрат 3x3 на поле» искать дайвера не
// годится — он стабильно показывает (15,10) и 72 байта, а это ОСЬМИНОГ, который
// с 2026-09-14 тоже жёлтый и крупнее дайвера.
//
//   const { teleport } = require("./diver_teleport.js");
//   const ok = teleport(m, S, row, col);   // поля встанут, спрайт — нет
module.exports.teleport = function teleport(m, S, row, col, tries = 60) {
  const D = S.DiverObj;
  for (let i = 0; i < tries; i++) {
    const r = m.rd(D + 0x19), c = m.rd(D);
    if (r === row && c === col) return true;
    if (c !== col) m.wr(D, col);
    if (r !== row) {
      const d = row - r;
      m.wr(D + 1, (m.rd(D + 1) + d) & 0xff);
    }
    // ХОД НЕ ГАСИМ. Обнуление +$04/+$05 каждый кадр останавливало не только
    // инерцию: дайвер переставал перерисовываться вовсе — жёлтый квадрат 3x3
    // оставался висеть на старом месте, а в новой клетке не появлялось ничего.
    m.step();
  }
  return m.rd(D + 0x19) === row && m.rd(D) === col;
};
