// ПОДБОР ЗНАЧЕНИЯ СКРОЛЛА СТЕНДОМ.
//
// Помечаем ОДНУ строку VRAM и смотрим, в какой строке кадрового буфера она
// показалась при разных значениях порта 3. Формуле vcr = vc + ~roll не доверяем:
// у неё граничные эффекты, а нам нужен ответ, а не вывод.
//
// ГРАБЛЯ ЗАМЕРА, стоившая двух прогонов: ScrollStart() читает io.PA, а io.output
// кладёт запись в ОТЛОЖЕННУЮ очередь, которую фиксирует луч в свой такт. Без
// исполнения команды out коммита не происходит, и обе первые версии мерили
// нетронутый скролл — все значения давали одинаковый результат. Пишем через
// realoutput, то есть туда, откуда развёртка читает.
//
// РЕЗУЛЬТАТ (кадровый буфер имеет отступ 16 строк сверху):
//   порт3=0xFF -> VRAM-строка 64 в строке буфера 80  (дефолт: VRAM 0 сверху)
//   порт3=0xC0 -> 17
//   порт3=0xBF -> 16   <- ЭТО ОНО: строка дисплея 0 = VRAM-строка 64
//   порт3=0xBE -> 271  (заворот)
//   порт3=0x80 -> 209
//   порт3=0x40 -> 145
"use strict";
const { make } = require("/Users/boris/projects/scubadive-i8080/tools/verify/harness.js");
const ROM="/Users/boris/projects/scubadive-i8080/build/pure/rastcal.rom";
const MARK_Y = 64;                      // помечаем VRAM-строку 64 (верх поля)
const W=576;
function probe(scroll){
  const m=make(ROM,{cpu:"i8080"});
  for(let i=0;i<8;i++) m.step();        // дать образу выставить палитру и очистить экран
  // гасим всё и метим одну строку: плоскость 0xC000, все столбцы, lo = 255-MARK_Y
  for(let a=0x8000;a<=0xFFFF;a++) m.wr(a,0);
  const lo=(255-MARK_Y)&255;
  for(let c=0;c<32;c++) m.wr(0xC000+c*256+lo,0xFF);
  // палитра: слот 2 (плоскость 0xC000) должен быть виден. Ставим напрямую.
  m.io.Palette[2]=0xFFFFFFFF; m.io.Palette[0]=0xFF000000;
  // ScrollStart() читает io.PA, а io.output кладёт запись в ОТЛОЖЕННУЮ очередь,
  // которую фиксирует луч в свой такт. Без исполнения команды out коммита не
  // происходит, и две прошлые версии замера мерили нетронутый скролл — все
  // значения давали один результат. Пишем туда, откуда читает развёртка.
  m.io.realoutput(3,scroll);
  // важно: снимок делаем БЕЗ исполнения кода образа, чтобы он не переписал порт
  m.v06c.check_breakpoint=()=>{ m.cpu.pc=m.cpu.pc; return false; };
  m.step();
  const bmp=m.v06c.bmp; const rows=[];
  for(let y=0;y<288;y++){ let n=0; for(let x=0;x<W;x++) if((bmp[y*W+x]>>>0)===0xFFFFFFFF) n++;
    if(n>10) rows.push(y); }
  return rows;
}
for(const v of [0xFF,0xC0,0xBF,0xBE,0x80,0x40]){
  const r=probe(v);
  console.log(`порт3=0x${v.toString(16).toUpperCase()}  VRAM-строка ${MARK_Y} видна в строках буфера: ${r.length?r.join(","):"не видна"}`);
}
