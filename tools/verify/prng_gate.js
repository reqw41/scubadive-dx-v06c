// значения снимаем на ВЫХОДЕ хелпера: ставим крючок на его ret нельзя, поэтому
// читаем ячейку-защёлку il_r и пересобираем то же, что вернул хелпер
function run(delayFrames, n) {
  const out = [];
  let m0 = null;
  const g = reachGame(rom, sym, { cpu: "i8080", level: 4, seed: 0x0167,
    preHook: (m, S) => {
      m0 = m;
      m.onPc(S.z80_ldar, () => {
        if (out.length >= n) return;
        // Читаем то, что положил ПРЕДЫДУЩИЙ вызов: хелпер сохраняет сырой младший
        // байт защёлки в il_r. Своё чтение порта здесь делать НЕЛЬЗЯ — защёлка
        // ВИ53 это автомат с состоянием, и лишняя пара out/in сбивает ту самую
        // величину, которую мы измеряем (на этом гейт сначала и врал).
        const lo = m.rd(S.il_r);
        out.push(((lo >> 1) | (lo << 7)) & 0x7f);   // как хелпер: rrca / and 7Fh
      });
    } });
  // Возмущение вносим ДО первого броска: держим клавишу лишние кадры на пути в
  // игру, отчего весь дальнейший ход программы смещается по тактам, а вместе с
  // ним и фаза счётчика. Это и есть проверка «сид не зашит в образ»: у прежнего
  // ЛКГ последовательность не зависела ни от чего.
  for (let i = 0; i < delayFrames; i++) g.m.step();
  g.m.key(KEY.UP, true);
  let guard = 0;
  while (out.length < n && guard < 400000) { g.m.step(); guard++; }
  return out;
}

function stats(name, s) {
  const n = s.length;
  if (!n) { console.log(`${name}: ПУСТАЯ ВЫБОРКА`); return null; }
  const uniq = new Set(s).size;
  const zeros = s.filter(v => v === 0).length;
  const mean = s.reduce((a, b) => a + b, 0) / n;
  const va = s.reduce((a, b) => a + (b - mean) * (b - mean), 0) / n;
  const ac = [1, 2, 3, 4, 8].map(lag => {
    let x = 0; for (let i = 0; i + lag < n; i++) x += (s[i] - mean) * (s[i + lag] - mean);
    return x / ((n - lag) * va);
  });
  console.log(`${name}: n=${n} различных значений=${uniq}/128 нулей=${zeros} (1/${(n / Math.max(1, zeros)).toFixed(1)}) ` +
              `среднее=${mean.toFixed(1)} автокорр=${ac.map(v => v.toFixed(3)).join(" ")}`);
  return { n, uniq, zeros, mean, ac };
}

const N = 20000;
const a = run(0, N), b = run(3, N);
const sa = stats("прогон A          ", a);
const sb = stats("прогон B (старт +7 кадров)", b);
let fail = 0;
if (!sa || sa.n < N * 0.9) { console.log("ПРОВАЛ: выборка не набралась"); fail++; }
else {
  if (sa.uniq < 100) { console.log(`ПРОВАЛ: счётчик почти не меняется (${sa.uniq} различных значений)`); fail++; }
  const rate = sa.n / Math.max(1, sa.zeros);
  if (rate < 90 || rate > 190) { console.log(`ПРОВАЛ: доля нулей 1/${rate.toFixed(1)}, ждали около 1/128`); fail++; }
  const worst = Math.max(...sa.ac.map(Math.abs));
  if (worst > 0.08) { console.log(`ПРОВАЛ: автокорреляция ${worst.toFixed(3)} — генератор предсказуем`); fail++; }
  // Сравниваем ТОЛЬКО хвост: до момента возмущения оба прогона идут по одинаковым
  // тактам и обязаны совпадать — эмулятор детерминирован. Смысл проверки в том,
  // что ПОСЛЕ сдвига ввода значения на тех же номерах вызова расходятся, потому
  // что зависят от протикавших тактов, а не от константы в образе.
  const SKIP = 3000;
  let same = 0;
  const k = Math.min(a.length, b.length);
  for (let i = SKIP; i < k; i++) if (a[i] === b[i]) same++;
  const frac = same / (k - SKIP);
  console.log(`совпадение хвостов прогонов A и B (после ${SKIP}-го вызова): ${(100 * frac).toFixed(1)}%; ` +
              `случайное совпадение двух независимых 7-битных последовательностей = 0.8%`);
  // СПРАВОЧНО, не критерий. Эмулятор детерминирован: одинаковый образ и
  // одинаковый ввод дают одинаковые такты, а значит и одинаковый счётчик. Доказать
  // недетерминизм на нём НЕЛЬЗЯ, и подгонять порог, чтобы получить зелёный, —
  // самообман. Структурный аргумент вместо него: в образе больше НЕТ ячейки-сида,
  // из которой выводится последовательность; значение берётся из счётчика ВИ53,
  // то есть из числа протикавших тактов. На железе такты зависят от момента
  // нажатия клавиш и от состояния счётчика при включении, которое ядро не
  // воспроизводит. Проверять это должен владелец на живой машине.
}
console.log(fail ? "ГЕЙТ КРАСНЫЙ" : "ГЕЙТ ЗЕЛЁНЫЙ: генератор живой, статистика в норме (недетерминизм — на железе, см. комментарий)");
process.exit(fail ? 1 : 0);
