// ГЕЙТ ГЕНЕРАТОРА (боевой образ, без DETERMINISTIC): источник случайности —
// свободно бегущий счётчик 0 ВИ53. Проверяем три вещи, которых не даёт
// фиксированный ЛКГ:
//  1) счётчик ЖИВОЙ: возвращаемые значения не константа и покрывают диапазон;
//  2) статистика не хуже настоящего регистра R Z80: доля нулей по маске 7Fh
//     около 1/128 и автокорреляция около нуля (у ЛКГ на лаге 3 было 0.162);
//  3) НЕТ фиксированного сида: два прогона с разным моментом старта дают разные
//     последовательности (у ЛКГ они совпадали байт в байт).
//   node tools/verify/prng_gate.js <rom> <sym>
"use strict";
const { reachGame, KEY } = require("./drive.js");

const rom = process.argv[2], sym = process.argv[3];

