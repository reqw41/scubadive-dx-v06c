#!/usr/bin/env python3
"""
genframe.py — тайлы рамки HUD в ДЫРЫ ШРИФТА.

Рамка оригинала не хранится битмапом: шесть знакомест (уголок в четырёх
ориентациях + горизонтальная и вертикальная палочки) кладутся в глифы символов
$3B..$40 (';' '<' '=' '>' '?' '@'). Эти глифы доказанно мертвы по переписи
шрифта: игра их не печатает нигде. Поэтому рамка стоит НОЛЬ байт данных — её
рисует обычная печать символов.

Уголки получаются поворотами/зеркалами одного рисунка, как и просил владелец,
но повороты считаются ЗДЕСЬ, на сборке, а не на Векторе.
"""
import os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# --- ГРАФИКА РАМКИ БЕРЁТСЯ ИЗ ПАНЕЛИ ОРИГИНАЛА -----------------------------
# Первая версия рисовала рамку СВОИМ узором, и владелец на железе сразу увидел,
# что это не зиминская панель. Теперь тайлы ВЫРЕЗАЮТСЯ из настоящей панели:
# scubapanl.asm распаковывается штатным salvador -d (сам файл не правится, он
# только читается), и из битмапа берутся готовые знакоместа.
#
# Что там на самом деле: рамка — ДВОЙНАЯ ЛИНИЯ С ПЕРЕКЛАДИНАМИ каждые 8 пикселей,
# одинаковый мотив по горизонтали и вертикали (лесенка). Поэтому поворот не нужен
# вовсе: у оригинала уже есть и горизонтальный, и вертикальный вариант кромки.
#   верхняя кромка  — строки 32..39 панели (внешняя линия на 33, внутренняя на 38)
#   нижняя кромка   — строки 216..223 (зеркально)
#   боковая кромка  — столбцы 24 и 31, рисунок .#....#. с перекладиной .#.##.#.
import subprocess, re, tempfile
def panel_bitmap():
    """распакованный битмап панели: 8 столбцов по 256 строк"""
    src = os.path.join(ROOT, "src8080", "scubapanl.asm")
    data = bytearray()
    for line in open(src, encoding="utf-8"):
        for m in re.finditer(r"\$([0-9A-Fa-f]{2})", line):
            data.append(int(m.group(1), 16))
    with tempfile.NamedTemporaryFile(suffix=".zx0", delete=False) as f:
        f.write(bytes(data)); zx0 = f.name
    raw = zx0 + ".bin"
    subprocess.run([os.path.join(ROOT, "tools", "bin", "salvador"), "-d", "-classic", zx0, raw],
                   check=True, capture_output=True)
    b = open(raw, "rb").read()
    assert len(b) == 2048, f"панель распаковалась в {len(b)} Б вместо 2048"
    return b
PANEL = panel_bitmap()
def cell(col, y0):
    """знакоместо 8x8 из панели: столбец 24..31, верхняя строка y0"""
    return [PANEL[(col - 24) * 256 + (255 - (y0 + r))] for r in range(8)]
# столбец 27 — середина кромки, там чистый горизонтальный узор без уголков
H_TILE  = cell(27, 32)
V_TILE  = cell(24, 40)
TL_TILE = cell(24, 32)
TR_TILE = cell(31, 32)
BL_TILE = cell(24, 216)
BR_TILE = cell(31, 216)

# КОРЫТО ШКАЛЫ — ПОВОРОТ ГРАФИКИ ОРИГИНАЛА. В панели шкала это сплошной столбец
# 8 пикселей шириной с насечками через каждые 8 строк (##....## по кромкам).
TROUGH_SRC = [0xFF] * 7 + [0b11000011]
def rot_cw(g):
    """поворот 8x8 на 90 градусов по часовой: out[r] бит c = in[7-c] бит r"""
    out = []
    for r in range(8):
        v = 0
        for c in range(8):
            if (g[7 - c] >> r) & 1:
                v |= 0x80 >> c
        out.append(v)
    return out
# После поворота насечки становятся ВЕРТИКАЛЬНЫМИ штрихами через каждые 8 пикселей
# длины — горизонтальная шкала получает разметку-линейку.
TROUGH = rot_cw(TROUGH_SRC)

# ТАБЛИЦА РАСТЯЖЕНИЯ для крупного заголовка: полубайт -> байт с удвоенными битами.
BIGTBL = []
for n in range(16):
    v = 0
    for i in range(4):
        if (n >> i) & 1:
            v |= 3 << (2 * i)
    BIGTBL.append(v)

TILES = [
    (0x22, BIGTBL[:8]),         # '"' таблица растяжения, младшая половина
    (0x23, BIGTBL[8:]),         # '#' таблица растяжения, старшая половина
    (0x21, TROUGH),             # '!' корыто шкалы (повёрнутая графика оригинала)
    (0x3B, H_TILE),             # ';' горизонтальная кромка (оригинал)
    (0x3C, V_TILE),             # '<' вертикальная кромка (оригинал)
    (0x3D, TL_TILE),            # '=' уголок левый верхний (оригинал)
    (0x3E, TR_TILE),            # '>' уголок правый верхний (оригинал)
    (0x3F, BL_TILE),            # '?' уголок левый нижний (оригинал)
    (0x40, BR_TILE),            # '@' уголок правый нижний (оригинал)
]
for p in ("src8080/scubasymb.asm", "src/scubasymb.asm"):
    f = os.path.join(ROOT, p)
    s = open(f, encoding="utf-8").read().split("\n")
    idx = {}
    for i, l in enumerate(s):
        if ";char" in l:
            # берём ТОЛЬКО первый токен: свой же комментарий вида ";char3B тайл рамки"
            # ломал разбор при повторном запуске (та же неидемпотентность, что была у genspec)
            try: idx[int(l.split(";char")[1].strip().split()[0], 16)] = i
            except ValueError: pass
    for ch, g in TILES:
        i0 = idx[ch]
        for b in range(8):
            s[i0 + b] = "\tDEFB %" + format(g[b], "08b") + (f"\t;char{ch:02X} тайл рамки HUD" if b == 0 else "")
    open(f, "w", encoding="utf-8").write("\n".join(s))
    print(p, "— шесть тайлов рамки вшиты в дыры шрифта")
for ch, g in TILES:
    print(f"  char {ch:02X}: " + " ".join(format(b, "08b").replace("0", ".").replace("1", "#") for b in g[:1]))
