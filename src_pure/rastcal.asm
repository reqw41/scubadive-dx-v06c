; ============================================================================
; СТЕРИЛЬНЫЙ КАЛИБРОВЩИК РАСТРОВОЙ ПАЛИТРЫ (самостоятельный .rom, игры нет)
; ============================================================================
; ЗАЧЕМ ОТДЕЛЬНЫЙ ОБРАЗ. Калибровочная лестница внутри игры оказалась нечитаемой:
; собственная графика игры перекрыла и границы, и линейку ступени. Здесь игры нет
; вовсе — ни спрайтов, ни рельефа, ни HUD. Все четыре плоскости залиты нулями,
; палитра известна побайтно, на экране ровно три вещи: линейка ступени, две
; контрольные красные линии и две растровые границы. Мусору взяться неоткуда,
; поэтому ЛЮБОЕ цветное пятно на экране — это промах залпа, и ничто другое.
;
; ЧТО ВИДНО НА ЭКРАНЕ (сверху вниз):
;   строки   0..7   жёлтые квадратики — НОМЕР СТУПЕНИ (1..16), считать слева;
;   строки   0..63  фон ГОЛУБОЙ  (слот 0 = небо);
;   строки  62..65  КРАСНАЯ полоса — контрольная линия первой границы;
;   строки  64..191 фон СИНИЙ    (слот 0 переключён залпом на строке 64);
;   строки 190..193 КРАСНАЯ полоса — контрольная линия второй границы;
;   строки 192..255 фон ЧЁРНЫЙ   (слот 0 переключён залпом на строке 192).
;
; КРИТЕРИЙ ДЛЯ ВЛАДЕЛЬЦА — ОДИН И ДВОИЧНЫЙ: **обе полосы остались КРАСНЫМИ.**
; Почему это работает. Контрольные полосы нарисованы в плоскости 0xE000, то есть
; имеют индекс цвета 1, и лежат ровно на тех строках, куда может упасть залп при
; промахе. Если залп попал в окно каймы — он пишет слот 0, полосы остаются
; красными. Если промахнулся и попал в поле — под лучом индекс 1, и залп
; защёлкивается в СЛОТ 1: обе полосы мгновенно становятся синими или чёрными.
; Палитра перезагружается целиком каждый кадр, поэтому на чистой ступени красный
; держится ровно, а на грязной ровно так же ровно держится неправильный цвет —
; мигания нет, спутать нельзя.
;
; ЛЕСТНИЦА. 16 ступеней по 12 тактов = 192 такта = ровно одна растровая строка.
; Окно каймы повторяется каждую строку, поэтому одной строки перебора достаточно
; при ЛЮБОМ систематическом сдвиге, хоть в пять строк: сдвиг на целое число строк
; мусора не даёт, он только двигает границу по вертикали. Ступень держится 150
; кадров (3 с), полный цикл 48 с.
;
; ПЕРЕНОСИМОСТЬ ОТВЕТА В ИГРУ. Счётчик взводится тем же способом и в той же фазе,
; что в игре: прерывание принимается ИЗ HALT, обработчик начинается с той же
; последовательности (push af, push hl, ld a,(rz_on), dec a, call z через
; трамплин), и взвод стоит первым. Поэтому найденная здесь ступень переносится в
; игру заменой одной константы RZ_Q. Совпадение фаз проверено на стенде:
; tools/verify/purecal_gate.js сверяет позицию залпа с игровой байт в байт.
; ============================================================================

RZ_SKY		EQU 0F8h	; голубой — небо, слот 0 в верхней зоне
RZ_WATER	EQU 0C0h	; синий   — вода, слот 0 после строки 64
RZ_HUD		EQU 000h	; чёрный  — фон HUD, слот 0 после строки 192
COL_RULE	EQU 007h	; красный — слот 1, контрольные полосы
COL_MARK	EQU 03Fh	; жёлтый  — слот 2, линейка ступени

; Константы рандеву — те же, что в src8080/scubarast.asm. Ступень 0 = штатное
; значение RZ_Q, чтобы лестница начиналась с фазы, откалиброванной на стенде.
RZ_THW		EQU 04Eh	; старший байт цели для строки 64
RZ_THH		EQU 01Eh	; старший байт цели для строки 192
RZ_K		EQU 246		; порог выхода тонкого опроса
RZ_Q		EQU 192		; младший байт, при котором цепочка NOP пуста
RZ_M		EQU 63		; длина цепочки NOP
CAL_FRAMES	EQU 150		; кадров на ступень

	OUTPUT "rastcal.bin"
	ORG 0100h

; ============================================================================
start:
	di
	xor a
	out (10h),a		; окно квазидиска выключить первой же командой
	ld sp,0100h
; вектор кадрового прерывания (RST 7)
	ld a,0C3h
	ld (38h),a
	ld hl,isr
	ld (39h),hl
; ППА в 0x88 и всё, что она сбрасывает, — СРАЗУ ПОСЛЕ неё. Урок саги полос
; (коммит 9b51fa6): запись режима ППА в порт 0 сбрасывает защёлки портов, включая
; скролл. Здесь режим пишется один раз при старте и больше не трогается — скан
; клавиатуры (0x8A) в этом образе не нужен вовсе.
	ld a,88h
	out (0),a
	ld a,2
	out (1),a
	ld a,0FFh
	out (3),a		; скролл
	xor a
	out (2),a		; кайма = индекс 0: любая запись 0x0C из окна каймы
				; попадает в слот 0 и никуда больше
; --- ЧИСТКА ВСЕХ ЧЕТЫРЁХ ПЛОСКОСТЕЙ 0x8000..0xFFFF -------------------------
; Это и есть «стерильность»: после неё индекс цвета равен нулю в каждой точке
; экрана, кроме того, что мы нарисуем сами.
	ld hl,8000h
clr:
	xor a
	ld (hl),a
	inc hl
	ld a,h
	or l
	jp nz,clr
; --- КОНТРОЛЬНЫЕ ПОЛОСЫ (индекс 1, плоскость 0xE000) -----------------------
; Адрес видеопамяти: плоскость + столбец*256 + (255 - строка_картинки).
; Строки 62..65 -> младшие байты 193..190; строки 190..193 -> младшие 65..62.
; Полосы по 4 строки: лестница двигает залп в пределах одной строки, значит
; промах не может уйти дальше соседней строки, и четырёх строк хватает с запасом.
	ld h,0E0h
rule_col:
	ld l,190
	call rule4
	ld l,62
	call rule4
	inc h
	ld a,h
	or a			; h завернулся из 0xFF в 0x00 -> все 32 столбца
	jp nz,rule_col
; --- пуск растра ------------------------------------------------------------
	ld a,1
	ld (rz_on),a		; 1 = взвести счётчик на ближайшем прерывании

; ============================================================================
; ГЛАВНЫЙ ЦИКЛ. Игры нет, поэтому ждать строку можно сколько угодно: рандеву
; выполняется КАЖДЫЙ кадр без исключений, пропущенных кадров не бывает в
; принципе. Это второе преимущество стерильного образа перед лестницей в игре,
; где длинные перерисовки съедали каждый пятый кадр.
; ============================================================================
main:
	ei
	halt
; здесь мы сразу после прерывания, в верхней кайме: окно записи палитры — целая
; строка, промахнуться нечем.
	call pal_load		; все 16 слотов из таблицы
	call sweep		; шаг лестницы и линейка ступени
	call rz_water		; рандеву к строке 64,  залп слот 0 := синий
	call rz_hud		; рандеву к строке 192, залп слот 0 := чёрный
	jp main

; --- четыре байта 0xFF подряд ----------------------------------------------
rule4:
	ld a,0FFh
	ld (hl),a
	inc l
	ld (hl),a
	inc l
	ld (hl),a
	inc l
	ld (hl),a
	ret

; --- обработчик прерывания --------------------------------------------------
; Голова обработчика ПОВТОРЯЕТ голову KEYINT игры команда в команду, включая
; трамплин: от этого зависит фаза взвода счётчика, а от неё — переносимость
; найденной ступени в игру.
isr:
	push af
	push hl
	ld a,(rz_on)
	dec a
	call z,rz_vec		; ровно rz_on==1 -> взвод
	pop hl
	pop af
	ei
	ret

rz_vec:
	jp rz_arm_do

rz_arm_do:
	ld a,74h		; канал 1, RL=11, режим 2, BCD=0
	out (8),a
	xor a
	out (0Ah),a		; младший байт делителя 0x7500
	ld a,75h
	out (0Ah),a		; старший — счётчик привязан к развёртке
	ld a,2
	ld (rz_on),a
	ret

; --- загрузка всех 16 слотов (в верхней кайме) ------------------------------
; Перезагрузка КАЖДЫЙ кадр обязательна: она стирает следы промаха предыдущего
; кадра, и потому цвет контрольных полос показывает состояние ТЕКУЩЕЙ ступени,
; а не историю.
pal_load:
	ld hl,paltab
	ld e,0
pl_loop:
	ld a,e
	out (2),a		; кайма показывает слот e -> пишем именно в него
	ld a,(hl)
	out (0Ch),a
	out (0Ch),a
	out (0Ch),a
	out (0Ch),a
	inc hl
	inc e
	ld a,e
	cp 16
	jp nz,pl_loop
	xor a
	out (2),a		; кайма обратно в слот 0
	ret

paltab:
	defb RZ_SKY, COL_RULE, COL_MARK, 0, 0, 0, 0, 0
	defb 0, 0, 0, 0, 0, 0, 0, 0

; --- шаг лестницы и линейка ступени ----------------------------------------
sweep:
	ld hl,rz_fcnt
	dec (hl)
	jp nz,bar
	ld (hl),CAL_FRAMES
	ld a,(rz_step)
	inc a
	and 15
	ld (rz_step),a
	ld l,a
	ld h,0
	ld de,rz_qtab
	add hl,de
	ld a,(hl)
	ld (rz_sub+1),a		; новая фаза — прямо в операнд команды довводки
; ЛИНЕЙКА СТУПЕНИ: метка j занимает столбец 2*j плоскости 0xC000 (индекс 2,
; жёлтый) и строки картинки 0..7. Рисуются ВСЕ 16 позиций каждый кадр, лишние
; гасятся нулём — иначе метки прошлой, более длинной ступени остались бы на
; экране и счёт бы врал.
bar:
	ld a,(rz_step)
	inc a
	ld d,a			; D = сколько меток закрасить, 1..16
	ld e,0
	ld b,16
	ld h,0C0h
bar_col:
	ld a,e
	cp d
	ld a,0FFh		; ld не трогает флаги — перенос от cp ещё жив
	jp c,bar_fill
	xor a
bar_fill:
	ld l,0F8h		; строка картинки 7 -> младший байт 255-7 = 248
bar_row:
	ld (hl),a
	inc l
	jp nz,bar_row		; 248..255 и заворот в 0 — ровно 8 байт
	inc e
	inc h
	inc h
	dec b
	jp nz,bar_col
	ret

; Таблица RZ_Q: шаг -6 единиц = +12 тактов задержки на ступень.
rz_qtab:
	defb 192,186,180,174,168,162,156,150
	defb 144,138,132,126,120,114,108,102

rz_on:		defb 0		; 0 выкл, 1 взвести, 2 взведён
rz_step:	defb 0		; номер ступени 0..15
rz_fcnt:	defb CAL_FRAMES	; кадров до следующей ступени

; ============================================================================
; РАНДЕВУ — код перенесён из src8080/scubarast.asm без изменений в тайминге.
; ============================================================================
; ДВА ЗАЛПА РАЗНОЙ ШИРИНЫ — ЭТО ВТОРОЙ ВОПРОС, КОТОРЫЙ ОБРАЗ ЗАДАЁТ ЖЕЛЕЗУ.
; Верхняя граница стреляет ЧЕТЫРЬМЯ записями (36 тактов, допустимая полоса фаз 28
; тактов), нижняя — ОДНОЙ (полоса 64 такта, вдвое шире). Если одиночная запись
; защёлкивает слот так же надёжно, как залп, то на лесенке нижняя полоса останется
; красной на БОЛЬШЕМ числе ступеней, чем верхняя. Ответ на это стоит дорого:
; одиночная запись — это два слота в строку вместо одного, то есть лесенка
; переключения палитры вдвое короче (8 строк вместо 16), а это ровно та разница,
; которая укладывает всю схему в бюджет 10% темпа.
; Ширина переключается подменой одного байта ВНЕ тактового пути: 0xD3 = опкод out
; (залп продолжается), 0xC9 = ret (залп обрывается после первой записи).
rz_water:
	ld a,0D3h
	ld (rz_shot_tail),a	; четыре записи
	ld b,RZ_WATER
	ld d,RZ_THW+1
	jp rz_go

rz_hud:
	ld a,0C9h
	ld (rz_shot_tail),a	; одна запись
	ld b,RZ_HUD
	ld d,RZ_THH+1
	; провал в rz_go

rz_go:
; ступень 1: дождаться старшего байта TH+1 — гарантия входа в блок TH СВЕРХУ.
; Протокол чтения: команда защёлки в порт 8, затем РОВНО два чтения из 0x0A.
rz_p1:
	ld a,40h
	out (8),a
	in a,(0Ah)
	in a,(0Ah)
	cp d
	jp nz,rz_p1
	dec d
; ступень 2: дождаться старшего байта TH. Петля 30 тиков против шага старшего
; байта в 256 тиков — проскочить значение невозможно. Именно на этом умер поллинг
; в indy-06: там ждали РАВЕНСТВА НУЛЮ петлёй в 30 тиков, ноль проскакивался, и
; ожидание висело навсегда (scroll.asm:379 «on MiSTer this poll can hang»).
rz_p2:
	ld a,40h
	out (8),a
	in a,(0Ah)
	in a,(0Ah)
	cp d
	jp nz,rz_p2
; ступень 3: тонкий опрос по младшему байту
rz_p3:
	ld a,40h
	out (8),a
	in a,(0Ah)
	ld e,a
	in a,(0Ah)
	ld a,e
	cp RZ_K+1
	jp nc,rz_p3
; довводка цепочкой NOP; защита снизу обязательна (замер в игре: без неё залп
; опаздывал на 128 тактов и уходил из окна в поле)
rz_sub:	sub RZ_Q
	jp nc,rz_ok
	xor a
rz_ok:
	or a
	rra
	and RZ_M
	cpl
	add a,RZ_M+1+low rz_chain
	ld l,a
	ld h,high rz_chain
	ld a,b
	jp (hl)
rz_chain:
	DS RZ_M, 0
	ASSERT high rz_chain == high rz_shot

; ЗАЛП. Первая запись стоит всегда, хвост включается подменой байта rz_shot_tail.
rz_shot:
	out (0Ch),a
rz_shot_tail:
	out (0Ch),a
	out (0Ch),a
	out (0Ch),a
	ret

	DISPLAY "PURE calibrator end: ", /A, $
	OUTEND
	END
