; =====================================================================
; ОТРАЖЁННАЯ СБОРКА КАДРА (-DMIRROR)
;
; Набор кадров для движения влево есть зеркало набора для движения вправо —
; 1976 байт графики лежат в игре дважды (замер: tools/verify/mirror_census.js).
; Второй экземпляр не хранится: кадр берётся из оставшегося набора и отражается
; на лету, при сборке в слот.
;
; ОТРАЖЕНИЕ ПО ГОРИЗОНТАЛИ — это две операции сразу: байты строки читаются с
; конца к началу, и в каждом переворачиваются биты. Переворот битов — таблицей
; MIR_TAB (256 байт, ALIGN 256): восемь сдвигов на байт стоили бы ~90 тактов и
; на кадре акулы дали бы лишние 15 000.
;
; СДВИГ НА k ДЕЛАЕТСЯ ТЕМ ЖЕ ПРИЁМОМ, ЧТО В ШТАТНОЙ СБОРКЕ, и теми же её
; настройками: вход в цепочку RRC (SH_b1+2) и маска младших битов FF>>k
; (SH_b1+6) уже посчитаны для этого кадра. Тождества строки те же:
;   X = rotr_k(байт);  out = (X & lo) | перенос;  перенос' = X ^ (X & lo).
; Отражать после сдвига было бы неверно: отражение меняет направление сдвига.
;
; Тело НЕ развёрнуто по ширине, в отличие от штатного: сборка кадра идёт раз на
; обновление существа, а не на каждый байт блита, и лишние ~30 тактов на байт
; здесь дешевле полутора сотен байт развёртки под потолком 0xA000.
; =====================================================================
; I: HL = начало строки источника, DE = приёмник, C = 0, (mir_w) = ширина строки
MirrorRow:
	ld a,(mir_w)
	dec a
	add a,l
	ld l,a
	ld a,0
	adc a,h
	ld h,a			; HL = последний байт строки: читаем справа налево
MR_row:
	ld a,(mir_w)
	ld b,a			; B = байтов в строке
	ld c,0			; перенос между байтами строки
MR_byte:
	ld a,(hl)
	push hl
	ld l,a
	ld h,HIGH MIR_TAB
	ld a,(hl)		; байт с перевёрнутыми битами
	pop hl
	dec hl			; следующий байт строки — левее
MR_rot:	call 0			; операнд: SH_rot0-k, ставится ниже
	ld (mir_x),a
MR_lo:	and 0			; операнд: FF>>k, ставится ниже
	or c
	ld (de),a
	inc de
	ld a,(mir_x)
MR_lo2:	and 0			; тот же операнд, что MR_lo
	ld c,a
	ld a,(mir_x)
	xor c
	ld c,a			; перенос = X ^ (X & lo)
	dec b
	jp nz,MR_byte
	ld a,c
	ld (de),a		; нулевой байт строки принимает хвост последнего
	inc de
; следующая строка источника: HL стоит слева от прошлой, шагнуть через две ширины
	ld a,(mir_w)
	add a,a
	add a,l
	ld l,a
	ld a,0
	adc a,h
	ld h,a
	ld a,e
MR_end:	cp 0			; операнд: тот же конец приёмника, что у SH_end
	jp nz,MR_row
; HL ОБЯЗАН ОСТАТЬСЯ НА КОНЦЕ КАДРА, как после штатного прохода: хвост сборки
; кладёт его в (IX+$0B/$0C), и по нему анимация ищет следующий кадр и конец
; цепочки. Штатный проход идёт вперёд и приходит ровно на начало+rows*w; наш
; читает строки справа налево и перешагивает на две ширины, поэтому оказывается
; на (w-1) байт дальше. Без этой поправки существо шагает по кадрам мимо и
; тащит на экран мусор — а стенд показывает лишь «картинка разошлась».
	ld a,(mir_w)
	dec a
	cpl
	inc a			; A = -(w-1)
	add a,l
	ld l,a
	ld a,0FFh
	adc a,h
	ld h,a
	ret
	ENDIF

