	IFDEF CLOUDINK
; =====================================================================
; ТРАКТ ВТОРОЙ ПЛОСКОСТИ ДЛЯ РАСКРАШЕННОЙ СТАЙКИ (-DCLOUDINK)
;
; Стайка — единственное существо, у которого рыбки разного цвета. Значит один
; проход блита её не нарисует: жёлтые рыбки идут в 0xC000, синие в 0xE000,
; красные в обе. Сделано это ДВУМЯ ПРОХОДАМИ одного и того же тракта:
;   проход 1 — маска из блока кадров (жёлтые и красные) в 0xC000, буфер
;              save-under на своём месте;
;   проход 2 — маска второй плоскости (синие и красные) в 0xE000, буфер
;              save-under во ВТОРОЙ половине той же страницы пула.
; Второй буфер не стоит ни страницы: слот стайки — 128 байт из 256-байтовой
; страницы, вторая половина пуста (у акулы и лодки слот занимает страницу
; целиком, но им второй проход и не нужен).
;
; МАСКА ВТОРОЙ ПЛОСКОСТИ РАЗВОРАЧИВАЕТСЯ СРАЗУ СО СДВИГОМ. Штатная сборка кадра
; (LB3A0) копирует кадр в слот, сдвигая на k пикселей; гонять её второй раз
; нельзя — она ведёт учёт по записи (конец кадра, ключ лодки) и повторный заход
; сбил бы анимацию. Поэтому здесь свой проход: распаковка и сдвиг разом, теми же
; настройками, что уже стоят в теле сборки (вход в цепочку RRC и маска младших
; битов взяты из её же патчей — SH_b1+2 и SH_b1+6).
; =====================================================================
; O: HL = упакованная маска этого кадра, Z — кадр раскрашен; иначе NZ.
; I: DE = адрес кадра (как в LB3FA).
CloudFind:
	push bc
	push de
	ld hl,CloudInkTab
	ld b,CLOUD_N
CloudFind_1:
	ld a,(hl)
	inc hl
	cp e
	jp nz,CloudFind_2
	ld a,(hl)
	cp d
	jp z,CloudFind_hit
CloudFind_2:
	inc hl
	inc hl
	inc hl			; к следующей записи (4 байта)
	dec b
	jp nz,CloudFind_1
	pop de
	pop bc
	or 1			; NZ — кадр не из стайки
	ret
CloudFind_hit:
	inc hl
	ld a,(hl)
	inc hl
	ld h,(hl)
	ld l,a			; HL = упакованная маска
	pop de
	pop bc
	xor a			; Z
	ret
	ENDIF

	IFDEF CLOUDINK
; РАЗВОРОТ МАСКИ ВТОРОЙ ПЛОСКОСТИ ПРЯМО В СЛОТ, СО СДВИГОМ НА k.
; I: HL = упакованная маска, DE = слот второй половины страницы.
; Формат распакованной строки в слоте — как у сборки: (IY+$07) = 4 байта, где
; четвёртый принимает хвост сдвига. Слот заполняется целиком: cl_pref строк
; нулей сверху (кадр стоит ниже верха слота ровно на столько), 24 строки кадра,
; остаток слота нулями — иначе в нём останется чужой кадр, и стайка потащит за
; собой хвост прошлого существа.
; Сдвиг делается теми же настройками, что уже стоят в теле сборки: вход в
; цепочку RRC (SH_b1+2) и маска младших битов после поворота (SH_b1+6).
CloudUnpack:
	ld a,(hl)
	ld (cl_map),a
	inc hl
	ld a,(hl)
	ld (cl_map+1),a
	inc hl
	ld a,(hl)
	ld (cl_map+2),a
	inc hl
	ld (cl_src),hl
	ld hl,(SH_b1+2)
	ld (CU_rot+1),hl	; тот же вход в цепочку поворотов, что у сборки
	ld a,(SH_b1+6)
	ld (CU_lo+1),a		; та же маска младших битов FF>>k
; префикс нулей: cl_pref строк по четыре байта
	ld a,(cl_pref)
	add a,a
	add a,a
	ld b,a
	or a
	jp z,CU_body
	xor a
CU_pre:
	ld (de),a
	inc de
	dec b
	jp nz,CU_pre
CU_body:
	ld hl,cl_map
	ld (cl_mapp),hl
	ld a,(hl)
	ld (cl_cur),a
	xor a
	ld (cl_carry),a
	ld c,24			; строк кадра
CU_row:
	ld a,(cl_cur)
	rrca
	ld (cl_cur),a
	jp nc,CU_empty
; строка есть: маска её байтов, затем сами непустые
	ld hl,(cl_src)
	ld a,(hl)
	inc hl
	ld (cl_bm),a
	ld b,3			; три байта строки
CU_byte:
	ld a,(cl_bm)
	rrca
	ld (cl_bm),a
	ld a,0			; пустой байт строки
	jp nc,CU_have
	ld a,(hl)
	inc hl
CU_have:
	push hl
CU_rot:	call 0			; операнд ставится выше: SH_rot0-k
	ld h,a
CU_lo:	and 0			; операнд ставится выше: FF>>k
	ld l,a			; L = младшая часть после поворота
	ld a,(cl_carry)
	or l
	ld (de),a		; байт слота = (X & lo) | перенос
	inc de
	ld a,h
	xor l			; X ^ (X & lo) — старшая часть уходит в следующий байт
	ld (cl_carry),a
	pop hl
	dec b
	jp nz,CU_byte
	ld (cl_src),hl
	jp CU_tail
CU_empty:
	ld a,0
	ld (de),a
	inc de
	ld (de),a
	inc de
	ld (de),a
	inc de
	xor a
	ld (cl_carry),a
CU_tail:
	ld a,(cl_carry)
	ld (de),a		; четвёртый байт строки — хвост сдвига
	inc de
	xor a
	ld (cl_carry),a
	dec c
	jp z,CU_pad
	ld a,c			; карта строк идёт байтами по восемь строк: считать
	and 7			; индекс от убывающего счётчика — значит ошибиться в
	jp nz,CU_row		; направлении, поэтому просто держим указатель
	ld hl,(cl_mapp)
	inc hl
	ld (cl_mapp),hl
	ld a,(hl)
	ld (cl_cur),a
	jp CU_row
; хвост слота нулями: до конца 32 строк
CU_pad:
	ld a,(cl_pref)
	ld b,a
	ld a,8
	sub b
	add a,a
	add a,a
	ld b,a
	or a
	ret z
	xor a
CU_pad1:
	ld (de),a
	inc de
	dec b
	jp nz,CU_pad1
	ret
	ENDIF

	IFDEF CLOUDINK
; рабочие ячейки тракта стайки
cl_map		DEFB 0,0,0	; карта непустых строк текущего кадра
cl_mapp		DEFW 0		; указатель на её текущий байт
cl_cur		DEFB 0		; байт карты, сдвигаемый по строке
cl_bm		DEFB 0		; маска непустых байтов текущей строки
cl_src		DEFW 0		; чтение упакованной маски
cl_carry	DEFB 0		; перенос сдвига между байтами строки
cl_pref		DEFB 0		; строк префикса в слоте (ставит сборка)
cl_mask		DEFW 0		; упакованная маска текущего кадра, 0 — тип не раскрашен
cl_pass		DEFB 0		; 1 — идёт второй проход блита (0xE000)
cl_row0		DEFB 0		; (IY+$03) до первого прохода: второй начинает с неё же
	ENDIF
