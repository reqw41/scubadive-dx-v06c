; ===== СХЛОПЫВАНИЕ ВЗРЫВА (-DEXPLFADE) ========================================
; Пожелание владельца 2026-09-04: взрыв дайвера не должен висеть все 256 тиков
; агонии до стирания экрана — пусть «проигрывается назад» до исчезновения.
; В оригинале кадр взрыва один и неподвижен (DiverExplosion ставит SprExplosion
; или SprExplosion+$20 и больше его не трогает), а тракт дайвера перерисовывает
; спрайт КАЖДЫЙ тик прямо из его байтов (проверено стендом: обнулил байты кадра
; на 20-м тике агонии — на 30-м на экране пусто). Поэтому:
;  * DiverExplosion копирует выбранный кадр (32 Б) в EXPL_BUF и переводит оба
;    указателя спрайта (+$09/+$0B) на копию — оригинал в скрытой плоскости цел;
;  * цикл смерти LD9F6 на каждом обороте зовёт ExplStage: стадия k = 0..7 по
;    счётчику B (256 оборотов, по 32 на стадию); стадия гасит в копии строки k и
;    15-k и столбцы k и 15-k (после 32 оборотов с целым кадром). Гашение идемпотентно, поэтому повторный вызов на
;    той же стадии безвреден и памяти под «последнюю стадию» не нужно. К k=7
;    кадр пуст — звезда сжимается к центру и гаснет за ~1.5 с, до стирания.
; ПАМЯТЬ: под потолком кода 0xA000 нет места, скрытая плоскость забита (клауды
; до 0xAFF8), поэтому копия живёт в пуле: четверть 63 ($BFC0..$BFFF) бронируется
; в LBEC7 битом 7 записи LB676+63 (как страница лодки). Пик занятости пула на
; ур.4 — 14 четвертей из 56, вычет одной ничего не стоит.
; Гибель без взрыва (утонул: кадр SprDrowned, LE3D2) ExplStage узнаёт по старшему
; байту указателя и ничего не делает.
	IFNDEF QPOOL
	.ERROR "EXPLFADE требует QPOOL: бронь четвертей пула"
	ENDIF
; РАЗМЕЩЕНИЕ. Под потолком кода 0xA000 места нет (перебор 36 Б даже после чистки),
; поэтому и копия, и код лежат в бронированных четвертях 61..63 пула
; ($BF40..$BFFF, 192 Б). Образ дотягивается сюда нулями (zx0 их почти не стоит),
; загрузчик кладёт код при старте, пул этот диапазон никогда не выдаёт (бит 7 в
; LB676+61..63 ставит LBEC7). Никто другой сюда не пишет: LC4D7 лишь считает
; DE=$B000+DelayVal, стейджинг — страница 0, лодка — страница 13.
EXPL_Q		EQU 61
	ASSERT $ <= POOL_HI*256+EXPL_Q*64
	DS POOL_HI*256+EXPL_Q*64-$, 0
EXPL_BUF:	DS 32			; копия кадра взрыва

; I: HL = кадр взрыва (SprExplosion или +$20). Портит A,B,D,E,HL.
ExplCopy:
	ld de,EXPL_BUF
	ld b,32
EC_l:	ld a,(hl)
	ld (de),a
	inc hl
	inc de
	dec b
	jp nz,EC_l
	ld hl,EXPL_BUF
	ld (DiverObj+$09),hl	; оба указателя (текущий и прежний кадр) — на копию
	ld (DiverObj+$0B),hl
	ret

; I: B = счётчик цикла смерти: 0 на первом обороте, затем 255..1.
; Стадия ((B-1) xor $FF) >> 5 = 0..7 (B=0 -> 0, B=255 -> 0, ..., B=1 -> 7); стадия 0 —
; кадр цел (взрыв виден целиком ~32 тика), стадии 1..7 -> k = 0..6.
ExplStage:
	ld a,(DiverObj+$0A)
	cp EXPL_BUF>>8
	ret nz			; кадр не наш (утонувший дайвер) — не трогаем
	ld a,b
	dec a
	cpl
	rlca
	rlca
	rlca
	and 7
	dec a			; первые 32 оборота кадр цел, дальше k = 0..6
	ret m
	ld c,a			; k
; строки k и 15-k: EXPL_BUF+2k и EXPL_BUF+30-2k — младший байт, четверть не пересекаем
	add a,a
	add a,EXPL_BUF&255
	ld l,a
	ld h,EXPL_BUF>>8
	ld (hl),0
	inc hl
	ld (hl),0
	ld a,(EXPL_BUF&255)+30
	sub c
	sub c
	ld l,a
	ld (hl),0
	inc hl
	ld (hl),0
; столбцы: левый байт — бит 7-k (маска D = ~($80>>k)), правый — бит k (E = ~(1<<k))
	ld d,80h
	ld e,1
	inc c
ES_s:	dec c
	jp z,ES_s0
	ld a,d
	rrca
	ld d,a
	ld a,e
	add a,a
	ld e,a
	jp ES_s
ES_s0:	ld a,d
	cpl
	ld d,a
	ld a,e
	cpl
	ld e,a
	ld hl,EXPL_BUF
	ld b,16
ES_r:	ld a,(hl)
	and d
	ld (hl),a
	inc hl
	ld a,(hl)
	and e
	ld (hl),a
	inc hl
	dec b
	jp nz,ES_r
	ret
	ASSERT $ <= POOL_HI*256+(EXPL_Q+3)*64	; три четверти: буфер + код
	DISPLAY "EXPLFADE end: ", /A, $
