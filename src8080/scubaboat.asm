; =====================================================================
; BOATFAST — дешёвое обновление ЛОДКИ (2026-08-29).
;
; Замер (tickdist/heavy_types): тики дольше кадра делает лодка — 192-байтный
; кадр собирается со сдвигом (~21 000 тактов) и блитится в бокс 8×32 (~35 000)
; при КАЖДОМ обновлении. Перерисовку убрать нельзя (она лечит save-under
; соседей — см. docs/speed_2026_08_27.md, кэш лодки), но её можно удешевить:
;
; 1. КАДР СОБИРАЕТСЯ ОДИН РАЗ. Сдвинутый кадр лодки живёт в собственной
;    странице пула BOAT_PAGE (страница 13 — бронь LBEC7, распределитель её не
;    выдаёт никогда), а не в стейджинге, который каждый тик затирает дайвер.
;    Ключ сборки: источник (адрес кадра после отката по FF), k (сдвиг) и
;    младший байт адреса назначения (префикс из (IX+$03)); хвост нулей C
;    определяется префиксом. Совпал ключ — сборка пропускается, остаётся только
;    учёт: (IX+$0B/$0C) := конец источника, запомненный при последней сборке.
;    LE682 (дайверы на лодке) правит сам источник — ключ сбрасывается.
;
; 2. БЛИТ СТОЛБЦОМ. Ширина лодки 8 байт, при ширине 8 шаг (IY+$0F) = 0 —
;    маска и буфер идут подряд 64 байта на столбец. Восемь строк без
;    построчного хвоста LB500_tail (~250 тактов на строку), строка из 8 байт
;    развёрнута. Семантика байта та же (XOR-композиция с save-under), картинка
;    байт в байт. Обрезанная краем поля лодка (blit_w < 8) идёт общим путём.
;
; КОД МОДУЛЯ — ОБЫЧНЫЙ КОД, адреса не выбирает (2026-08-30: раньше стоял по
; фиксированному 0xBE00 в страницах 14..15 пула, потому что код упирался в
; потолок 0xA000; после чистки места хватает, страницы вернулись в пул).
; ЕДИНСТВЕННЫЙ фиксированный адрес — BOAT_PAGE: страница 13 пула, её и только её
; бронирует LBEC7. С растровым модулем (ORG 0BD00h) несовместим по ней же —
; ASSERT в scubacod1.asm.
; =====================================================================
BOAT_PAGE	EQU 0BD00h	; кадр лодки, собранный со сдвигом (страница 13 пула)
BOAT_DESC	EQU LC092	; описатель лодки (IY)

boat_key	DEFB 0FFh,0,0,0	; k, источник lo/hi, назначение lo; k=FF — ключа нет
boat_bend	DEFW 0		; конец источника после последней сборки
boat_bld	DEFB 0		; 1 = текущая сборка кадра — лодка

; Z — IY указывает на описатель лодки. Портит только A.
IsBoatIY:
	ld a,(z80_iy)
	cp low BOAT_DESC
	ret nz
	ld a,(z80_iy+1)
	cp high BOAT_DESC
	ret

; HL = страница сборки кадра: стейджинг, для лодки — BOAT_PAGE. Портит A.
BoatBuf:
	ld hl,(LB7B9)
	call IsBoatIY
	ret nz
	ld hl,BOAT_PAGE
	ret

; Вход SH_k: B = k, DE = источник, HL = назначение. Z — лодка с прежним ключом,
; сборку можно пропустить. Иначе ключ запоминается (для лодки). Бережёт B, DE, HL.
BoatKey:
	call IsBoatIY
	jp nz,BoatKey_no
	ld a,(boat_key)
	cp b
	jp nz,BoatKey_new
	ld a,(boat_key+1)
	cp e
	jp nz,BoatKey_new
	ld a,(boat_key+2)
	cp d
	jp nz,BoatKey_new
	ld a,(boat_key+3)
	cp l
	ret z			; Z — ключ совпал
BoatKey_new:
	ld a,b
	ld (boat_key),a
	ld a,e
	ld (boat_key+1),a
	ld a,d
	ld (boat_key+2),a
	ld a,l
	ld (boat_key+3),a
	ld a,1
	ld (boat_bld),a
	ret			; NZ (A=1 после ld — флаги от последнего cp: NZ)
BoatKey_no:
	xor a
	ld (boat_bld),a
	or 1			; NZ
	ret

; SH_tail: DE = конец источника. Для лодки — запомнить. Бережёт DE, HL.
BoatEnd:
	ld a,(boat_bld)
	or a
	ret z
	ex de,hl
	ld (boat_bend),hl
	ex de,hl
	ret

; Пропуск сборки (SH_k, стек: [назначение][источник]): DE := конец источника,
; остальное как SH_tail.
BoatSkip:
	pop de			; источник — мёртв
	pop hl			; назначение
	push hl			; LB438 вернёт его
	ld hl,(boat_bend)
	ex de,hl		; DE = конец источника
	jp SH_tail1

; Столбец лодки одним проходом. Вход как у LB4FB: HL = экран (начало верхней
; строки столбца), DE = буфер, (z80_ix) = маска, B = 8, на стеке PUSH BC из
; LB4D6. Выход — LB500_colend с HL = начало − 8 (как после общего пути).
	MACRO BOAT_BYTE_M
	ld a,(de)		; байт буфера
	xor (hl)		; t = буфер XOR экран
	ld (hl),a		; t на экран — временный операнд
	ld a,(bc)		; маска
	or (hl)			; X = маска | t
	xor (hl)		; Y = маска & ~t
	ld (de),a		; новый буфер
	xor (hl)		; X снова
	ld (hl),a		; новый экран
	inc de
	inc bc
	ENDM
; ШИРИНА — ИЗ САМОМОДИФИЦИРОВАННОГО ОПЕРАНДА, А НЕ ИЗ blit_w. Вызывающий только
; что положил в LB500_end+1 конец столбца = H + (IY+$0E), а H с тех пор не менялся:
; разность и есть ширина. Отдельная ячейка blit_w была её копией и живёт теперь
; только под BLUEWRITE, где нужна восстановлению ватерлинии.
BoatCol:
	ld a,(LB500_end+1)
	sub h
	cp 8
	jp nz,LB4FB		; обрезана краем поля — общий путь
	ld (il_scr),hl
	ld hl,(z80_ix)
	ld b,h
	ld c,l			; BC = маска, 64 байта подряд (шаг (IY+$0F) = 0)
	ld hl,(il_scr)
	ld a,l
	sub 8
	ld (BoatCol_end+1),a	; L после восьми строк
BoatCol_row:
	REPT 7
	BOAT_BYTE_M
	inc h
	ENDR
	BOAT_BYTE_M
	ld a,h
	sub 7
	ld h,a			; назад в первый столбец
	dec l			; следующая строка
	ld a,l
BoatCol_end:
	cp 0			; операнд ставится в BoatCol
	jp nz,BoatCol_row
	ld h,b
	ld l,c
	ld (z80_ix),hl		; маска += 64; (IY+$07) = 8 — инвариант лодки, не трогаем
	ld hl,(il_scr)
	ld a,l
	sub 8
	ld l,a			; HL = начало − 8
	jp LB500_colend
BOAT_END:
	DISPLAY "BOAT module end: ", /A, BOAT_END
; Сторож потолка снят вместе с переездом: модуль лежит в общем коде, а его
; потолок — единый ASSERT SCUBACOD1_END в конце scubacod1.asm.
