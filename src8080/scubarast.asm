; ============================================================================
; ДИАГНОСТИЧЕСКИЙ РАСТРОВЫЙ ФОН (сборка -DRASTER, штатных образов не касается)
; ============================================================================
; ЧТО ДЕЛАЕТ. Слот 0 палитры (фон всего поля) перекрашивается ТРИ раза за кадр:
;   в гашении (KEYINT)     -> RZ_SKY   голубой  = небо
;   на растровой строке 64 -> RZ_WATER синий    = вода
;   на растровой строке 192-> RZ_HUD   чёрный   = фон HUD
; Цвета выбраны НАРОЧНО контрастными: проверяется МЕХАНИЗМ, а не арт. Строка
; ватерлинии зафиксирована на 64 и от сцены не зависит.
;
; ПОЧЕМУ ТАЙМЕР, А НЕ СЧЁТ ЦИКЛАМИ. Разбор — docs/vi53_line_timer.md. Коротко:
; цикловой отсчёт строк накапливает ошибку и зависит от фазы входа в прерывание
; (на этом умер эксперимент с полосами, docs/experiment_B_bands_palette.md), а
; счётчик ВИ53 даёт АБСОЛЮТНУЮ позицию внутри кадра. Канал 1 (порт 0x0A) в
; геймплее свободен: канал 0 занят ГПСЧ, канал 2 — мелодией.
;
; ЧЕГО ТАЙМЕР НЕ РЕШАЕТ. Слот палитры выбирается НЕ адресом, а цветом, который
; луч показывает в момент out (0x0C). В кайме это индекс из порта 2, поэтому в
; RASTER-сборке BorderColor принудительно 0: кайма всё время показывает слот 0,
; и любая запись в 0x0C из окна каймы попадает именно в него. Побочный эффект
; ОЖИДАЕМЫЙ и полезный: кайма сама перекрашивается на тех же строках — по фото
; с железа видно, где легли границы, даже если поле почему-то не перекрасилось.
;
; ГДЕ ЖИВЁТ МОДУЛЬ. ORG 0BD00h — верхняя страница пула буферов. Страницы 13..15
; ($BD00..$BFFF) забронированы (бит 7 в таблице LB676), распределитель их не
; выдаёт, это проверяет pool_gate. Так модуль не сдвигает ни одного байта игры и
; не бьётся о потолок кода $B000 (свободных байт там было 135).
; ============================================================================

RZ_SKY		EQU 0F8h	; голубой: B=11 G=111 R=000
RZ_WATER	EQU 0C0h	; синий:   B=11 G=000 R=000
RZ_HUD		EQU 000h	; чёрный

; --- цели счётчика ---------------------------------------------------------
; Канал 1, режим 2, делитель 0x7500 = 29952 тика = РОВНО кадр (59904 такта / 2).
; Счётчик считает ВНИЗ и сам перезагружается, то есть после единственного взвода
; он и есть регистр позиции в кадре: C = 29952 - (такты_от_взвода)/2.
; Взвод делается ОДИН раз и в детерминированной фазе: игра ставит rz_on=1 и
; уходит в halt, взвод исполняется из KEYINT на фиксированном смещении от
; прерывания. Отсюда и постоянство целей.
;
; Строка картинки Y начинается через 192*(40+Y) тактов после прерывания, а окно
; каймы (64 такта, из них 40 в гасящем ходе) лежит ПЕРЕД ней — то есть граница
; строки Y пишется в хвосте строки Y-1. Обе цели кратны 256 тикам с точностью до
; калибровки, поэтому ловятся сравнением ОДНОГО старшего байта.
;
; Числа ниже — не из формул, а с замера стенда (tools/verify/raster_gate.js
; печатает фактические строку и пиксель каждой записи). Формула даёт ожидание,
; замер — истину; на живом железе фаза взвода может отличаться, и тогда крутить
; надо RZ_Q (шаг 1 = 4 такта = 1/48 строки), а при сдвиге больше строки — RZ_THW
; и RZ_THH (шаг 1 = 256 тиков = 2.67 строки).
RZ_THW		EQU 04Eh	; старший байт цели для строки 64
RZ_THH		EQU 01Eh	; старший байт цели для строки 192
RZ_K		EQU 246		; порог выхода тонкого опроса по младшему байту
RZ_Q		EQU 192		; младший байт, при котором цепочка NOP пуста
RZ_M		EQU 31		; длина цепочки NOP (шаг 4 такта)

; ============================================================================
; ДЫРА ДО 0BD00h ВЫПИСЫВАЕТСЯ ЯВНО, а не задаётся ORG. Замер: sjasmplus --raw
; кладёт байты В ПОРЯДКЕ ВЫДАЧИ и пропуск адресов не заполняет — с голым ORG
; модуль лёг бы сразу за концом кода (0xAF88), а его собственные адреса остались
; бы от 0xBD00, и первый же переход по трамплину улетел бы в пустое место.
; Три с половиной тысячи нулей ZX0 давит почти в ноль, цена в образе — единицы
; байт, а при распаковке они ложатся в буферный пул, где ещё нет ничего.
	ASSERT $ <= 0BD00h
	DS 0BD00h-$, 0
; ============================================================================
; ТРАМПЛИНЫ ПО ФИКСИРОВАННЫМ АДРЕСАМ. Блок кода0 (там KEYINT) ассемблируется
; ОТДЕЛЬНЫМ проходом и меток блока кода1 не видит — экспорт идёт только в одну
; сторону, из кода0 в код1. Поэтому обработчик прерывания зовёт нас по числам,
; а числа заданы здесь и сверены ASSERT'ами: разъехаться молча они не могут.
rz_vec:
	jp rz_arm_do		; 0BD00h — взвод счётчика (rz_on == 1)
	jp rz_isr		; 0BD03h — залп неба в гашении
	ASSERT rz_vec == 0BD00h

; --- взвод счётчика, зовётся из KEYINT РОВНО ОДИН РАЗ (rz_on == 1) ----------
; Смещение от прерывания до записи старшего байта делителя постоянно: игра
; входит сюда из halt, а путь по KEYINT до этого места безусловный.
rz_arm_do:
	ld a,74h		; SC=01 (канал 1), RL=11 (мл,ст), M=010 (режим 2), BCD=0
	out (8),a
	xor a
	out (0Ah),a		; младший байт делителя 0x7500
	ld a,75h
	out (0Ah),a		; старший — с этого мига счётчик привязан к развёртке
	ld a,2
	ld (rz_on),a		; 2 = взведён, рандеву разрешено
	ret

; --- залп неба, зовётся из KEYINT после восстановления каймы ---------------
; Здесь мы в вертикальном гашении, кайма показывает слот 0 всю строку — окно
; шириной в кадр, промахнуться нечем.
; Состояние 3 значит «последний залп и выключиться»: игра кончилась, и слот 0
; надо вернуть в ColorNone (чёрный), иначе меню и таблица рекордов останутся на
; голубом фоне — рандеву в них уже не зовётся, а небо из прерывания красилось бы
; вечно. Возврат делается ЗДЕСЬ, потому что это единственное место, про которое
; известно, что мы в гашении.
rz_isr:
	ld a,(rz_on)
	dec a
	dec a
	dec a
	jp nz,rz_isr_sky
	ld (rz_on),a		; A уже 0 — выключено
	jp rz_shot		; и A уже 0 — это ColorNone, штатный фон игры
rz_isr_sky:
	ld a,RZ_SKY
	jp rz_shot

; --- рандеву к ватерлинии (строка 64), залп := вода -------------------------
; ПРОЗРАЧНОСТЬ ПО РЕГИСТРАМ И ФЛАГАМ ОБЯЗАТЕЛЬНА: вызовы стоят между CALL LB213
; и CALL LBDEA главного цикла, и что из регистров живёт через эту границу —
; вопрос, на который у нас нет доказательства. Поэтому сохраняем ВСЁ, включая
; флаги, и делаем это ДО проверки флага rz_on, а не после.
rz_water:
	push af
	push bc
	push de
	push hl
	ld a,(rz_on)
	cp 2
	jp nz,rz_ret		; счётчик ещё не взведён — молчим
	ld b,RZ_WATER
rz_pw:	ld d,RZ_THW+1		; операнд по rz_pw+1 — точка подсадки для гейта
	call rz_go
rz_ret:
	pop hl
	pop de
	pop bc
	pop af
	ret

; --- рандеву к границе HUD (строка 192), залп := чёрный ---------------------
rz_hud:
	push af
	push bc
	push de
	push hl
	ld a,(rz_on)
	cp 2
	jp nz,rz_ret
	ld b,RZ_HUD
rz_ph:	ld d,RZ_THH+1		; операнд по rz_ph+1
	call rz_go
	jp rz_ret

; ============================================================================
; ЯДРО РАНДЕВУ. Вход: B = значение слота, D = старший байт цели + 1.
; Три ступени, как в docs/vi53_line_timer.md разделе 5.3.
; ============================================================================
rz_go:
; --- ступень 1: дождаться старшего байта TH+1 ------------------------------
; Она нужна не для точности, а для БЕЗОПАСНОСТИ: гарантирует, что в блок TH мы
; входим СВЕРХУ, с младшим байтом около 255. Без неё вызов, случившийся уже
; внутри блока TH, вывалился бы из ступени 3 с младшим байтом меньше RZ_Q,
; вычитание ушло бы в минус и переход по цепочке улетел бы мимо кода.
; Протокол чтения строго по документации: команда защёлки в порт 8, затем РОВНО
; два чтения из 0x0A. Без защёлки настоящая ВИ53 отдаёт мусор (GATE прибит к
; единице, счёт не остановить), а лишнее или недостающее чтение навсегда сбивает
; чётность и вешает защёлку.
rz_p1:
	ld a,40h		; SC=01, RL=00 -> защёлка канала 1
	out (8),a
	in a,(0Ah)		; младший, выбрасываем
	in a,(0Ah)		; старший
	cp d
	jp nz,rz_p1
	dec d
; --- ступень 2: дождаться старшего байта TH --------------------------------
; Петля 60 тактов = 30 тиков, шаг старшего байта 256 тиков: проскочить значение
; физически невозможно, поэтому сравнение на равенство корректно.
rz_p2:
	ld a,40h
	out (8),a
	in a,(0Ah)
	in a,(0Ah)
	cp d
	jp nz,rz_p2
; --- ступень 3: тонкий опрос по младшему байту -----------------------------
; Петля 80 тактов = 40 тиков. Выходим, когда до цели осталось меньше RZ_K тиков,
; и в A лежит ТОЧНОЕ расстояние до цели в тиках, снятое той же защёлкой.
rz_p3:
	ld a,40h
	out (8),a
	in a,(0Ah)
	ld e,a			; младший байт сохраняем
	in a,(0Ah)		; старший — он же снимает защёлку
	ld a,e
	cp RZ_K+1
	jp nc,rz_p3
; --- довводка: остаток добираем цепочкой NOP -------------------------------
; n = (младший - RZ_Q)/2 штук NOP по 4 такта, вход в цепочку с конца.
;
; ЗАЩИТА СНИЗУ — НЕ ПЕДАНТИЗМ, А ЗАМЕР. Первая версия обходилась без неё, и
; стенд поймал ровно тот случай, ради которого она нужна: когда младший байт на
; выходе оказывается чуть НИЖЕ RZ_Q, вычитание уходит в минус, беззнаковый сдвиг
; даёт около 127, маска оставляет около 31 — и залп опаздывает на 128 тактов,
; вылезая из окна каймы прямо в поле (замер: 15 залпов из 239 по воде и 36 из
; 239 по HUD, и все они защёлкивали ЧУЖИЕ слоты 1, 4, 9, 11). Промах вниз значит
; «мы уже опоздали», и единственный правильный ответ на него — стрелять
; немедленно, а не ждать ещё 128 тактов.
; jp nc на Векторе стоит 12 тактов независимо от того, взят переход или нет,
; поэтому защита не сдвигает нормальный путь ни на такт.
rz_sub:	sub RZ_Q		; операнд по rz_sub+1 — точка подсадки для гейта
	jp nc,rz_ok
	xor a			; промах вниз: залп без задержки
rz_ok:
	or a			; сбросить перенос перед rra
	rra			; A = n
	and RZ_M		; страховка сверху: переход обязан остаться в цепочке
	cpl
	add a,RZ_M+1+low rz_chain	; A = младший байт входа = rz_chain + (RZ_M - n)
	ld l,a
; ВЫСОКИЙ БАЙТ — КОНСТАНТА, а не сложение HL+DE. Так короче на 24 такта, а 24
; такта здесь дороже байтов: чем короче постоянная часть, тем ниже RZ_Q, а чем
; ниже RZ_Q, тем больше запас до промаха вниз. Условие корректности —
; цепочка и залп целиком внутри одной страницы, это проверено ASSERT'ом.
	ld h,high rz_chain
	ld a,b			; цвет — в аккумулятор, залп пишет его
	jp (hl)
rz_chain:
	DS RZ_M, 0		; RZ_M байт 0x00 = NOP, вход в любую точку
	ASSERT high rz_chain == high rz_shot	; вход в цепочку считается по младшему байту

; --- ЗАЛП: ПЯТЬ ЗАПИСЕЙ ПОДРЯД, БЕЗ ПРОКЛАДОК ------------------------------
; ЗДЕСЬ Я ОТСТУПИЛ ОТ ОБРАЗЦА svofski (шесть out с прокладками, brdtestx.asm) И
; ВОТ ЗАМЕР, КОТОРЫЙ ЭТОГО ПОТРЕБОВАЛ. Окно каймы — 256 точек = 64 такта на
; строку. Прокладка добавляет к шагу 4 такта: шесть out через nop растягиваются
; на 92 такта = 368 точек, то есть В ПОЛТОРА РАЗА ШИРЕ ОКНА. Стенд показал ровно
; то, чем это кончается: из шести записей в окно попали две, а четыре легли в
; ПОЛЕ и защёлкнулись в слоты 3, 4 и 5 — с точки зрения экрана это не «цветная
; рябь по краю», а перекрашенный рельеф и цветной мусор по всему кадру ниже
; границы (в игре все 16 слотов заняты: палитра сделана четырьмя одинаковыми
; четвёрками, потому что в индекс цвета входят и невидимые плоскости).
; Пять out подряд — это 4 шага по 12 тактов = 192 точки, с запасом внутри окна
; (36 точек слева, 27 справа при нынешней калибровке). Страховка залпом от
; УЗОСТИ записи сохранена, лишнее выброшено.
; Прокладки у svofski страховали дрейф момента записи; у нас дрейфа нет — есть
; абсолютные часы и довводка до ±4 тактов.
rz_shot:
	out (0Ch),a
	out (0Ch),a
	out (0Ch),a
	out (0Ch),a
	out (0Ch),a
	ret

; --- пуск: зовётся из главного цикла игры один раз на вход в уровень -------
; ei+halt нужны не для красоты: взвод обязан случиться в ДЕТЕРМИНИРОВАННОЙ фазе
; кадра. Прерывание, принятое из halt, входит в KEYINT всегда одинаково, а
; принятое из работающего кода — с разбросом в длину текущей команды.
rz_start:
	push af
	ei
	ld a,1
	ld (rz_on),a
	halt
	pop af
	ret

; --- останов: зовётся на выходе из Game (game over) ------------------------
; Ставит состояние 3 и ждёт прерывания — оно вернёт слоту 0 чёрный и выключит
; растровый фон. Без этого меню осталось бы на голубом фоне.
rz_stop:
	push af
	ei
	ld a,3
	ld (rz_on),a
	halt
	pop af
	ret

	ASSERT $ <= 0BE00h	; модуль обязан уместиться в забронированную страницу
	DISPLAY "RASTER module end: ", /A, $
