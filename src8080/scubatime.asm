; =====================================================================
; TIMEBASE — ИГРОВОЕ ВРЕМЯ ОТ ПРЕРЫВАНИЯ (2026-09-03, решение владельца).
;
; Было: игровое время = число тиков главного цикла. На тяжёлой сцене тиков
; меньше — дайвер и существа в секундах медленнее (ур.4 в глубине: 77 тик/с,
; 5.5 шага дайвера в секунду против 13 в оригинале).
; Стало: единица времени u = 1/175 с (3.5 u на кадр 50 Гц — ровно один тик при
; штатном темпе pace_tick). tb_tick раз за тик считает Δ — сколько единиц
; прошло; счётчики существ, дайвера и таймеров уменьшаются на Δ, срабатывание
; «дошёл до нуля или ниже», перелёт переносится в перезарядку.
; На лёгкой сцене (3.5 тика/кадр) Δ == 1 всегда — поведение как раньше.
; Спецификация и проверка аккумулятора: tools/verify/timebase_spec.py.
; Арифметика точна для счётчиков 0..255 (у группы V есть мусорные слоты с 255):
; A = t + ~Δ = t-Δ-1, перенос ЕСТЬ <=> t >= Δ+1 <=> ещё не досчитал.
; TB_FIXED=1 — Δ принудительно 1 (доказательство обвязки: образ обязан
; совпасть с обычным байт в байт).
; =====================================================================
tb_acc:		DEFB 0		; запас времени в четвертях единицы после номинального 1 u за тик
tb_last:	DEFB 0		; FRAMES на прошлом тике
tb_delta:	DEFB 1		; Δ текущего тика, 1..8
tb_over:	DEFB 0		; перелёт последнего срабатывания
tb_force1:	DEFB 0		; ≠0 — залповый цикл (LEF12): Δ = 1
tb_ent:		DEFB 0		; вход в развёртку (11 байт на тело)
; КАЛИБРОВКА ПО ZX (2026-09-07, решение владельца). Темп оригинала на MAME с
; настоящей лентой (tools/verify/zx/tempo_game.lua, окна 5 с): ныряльщик В ЛОДКЕ —
; 142–150 тиков/с (ур.1 и ур.4), ПЛЫВЁТ (тяга, с поворотами и без) — 172–205,
; среднее ~185. У ZX время игры = тики, поэтому у нас единица времени идёт с двумя
; скоростями по состоянию дайвера (DiverObj+$10 бит 7 — в воде). Масштаб
; аккумулятора ×4: за кадр прибавляется TB_RATE_* = 4·u/кадр, за тик вычитается 4.
;   лодка: 12 = 3.0 u/кадр = 150 u/с (ZX 146);  вода: 15 = 3.75 u/кадр = 187.5 u/с (ZX 185).
; Было: 7 полуединиц за кадр = 175 u/с везде — у лодки существа шли на 13 % быстрее
; ZX, в воде на 5 % медленнее (сверка creature_speed.js/.lua по шагам/с).
	IFNDEF TB_RATE_BOAT
TB_RATE_BOAT	EQU 12
	ENDIF
	IFNDEF TB_RATE_SWIM
TB_RATE_SWIM	EQU 15
	ENDIF
	IFNDEF TB_DMAX
TB_DMAX		EQU 6		; потолок Δ. Было 4 (2026-09-04: 8 с долгом давало спираль после гибели); 2026-09-07 без
				; долга и при калибровке по ZX 4 срезал ур.4 у лодки до 128 ед/с из 150 (тики
				; идут пачками, излишек над потолком пропадает); 6 даёт 147, после возрождения 148
	ENDIF
SCAN_BODY_TB	EQU 11		; ld a,(hl) 1 + add a,c 1 + inc a 1 + ld (hl),a 1 + jp c 3 + call 3 + add hl,de 1

; --- tb_tick: раз за тик, в начале LB213. Портит A, B, HL. ------------------
tb_tick:
	IFDEF TB_FIXED
	jp tb_one
	ENDIF
	ld a,(tb_force1)
	or a
	jp nz,tb_one
	ld hl,tb_last
	ld a,(FRAMES)
	ld b,a
	sub (hl)		; df = кадров прошло
	ld (hl),b		; last := FRAMES
	cp 5
	jp nc,tb_pause		; пауза (смена экрана): мир стоял, время не догоняем
	push bc			; C вызывающего бережём (B и так портим)
	ld b,a
	ld a,(DiverObj+$10)
	and 80h			; бит 7 — дайвер в воде
	ld c,TB_RATE_SWIM
	jp nz,tb_rate_ok
	ld c,TB_RATE_BOAT
tb_rate_ok:
	ld hl,tb_acc
	ld a,(hl)
	sub 4			; номинальная единица за тик (масштаб ×4)
tb_addf:
	dec b
	jp m,tb_take
	add a,c			; + 4·u за кадр по состоянию
	jp tb_addf
tb_take:
	pop bc
	ld (hl),a		; acc
	or a
	jp m,tb_neg		; запаса нет — Δ = 1
	rrca
	rrca
	and 3Fh			; extra = acc/4
	cp TB_DMAX
	jp c,tb_ok
; ПОТОЛОК Δ: сцена не тянет реальное время. Долг сверх потолка НЕ копим —
; мир замедляется плавно, а не рывками вдогонку (замер 2026-09-04: после гибели
; у поверхности ур.4 тик 2.6 кадра, Δ=8, долг рос).
	ld a,TB_DMAX
	ld (tb_delta),a
	ld (hl),0		; acc := 0
	ret
tb_ok:
	ld b,a
	inc a
	ld (tb_delta),a		; Δ = 1 + extra
	ld a,b
	add a,a
	add a,a
	ld b,a
	ld a,(hl)
	sub b
	ld (hl),a		; acc -= 4*extra
	ret
tb_neg:
	cp 0F0h			; acc < -16 — тики бегут впереди времени: не копим
	jp nc,tb_one
	ld a,0F0h
	ld (hl),a
	jp tb_one
tb_pause:
	xor a
	ld (tb_acc),a
tb_one:
	ld a,1
	ld (tb_delta),a
	ret

; --- tb_dec: (HL) -= Δ. Выход: NC — досчитал (tb_over = перелёт); C — ещё нет.
; Портит только A и флаги. ------------------------------------------------
tb_dec:
	ld a,(hl)
	or a
	jp nz,tb_dec1
; t = 0: у `dec (hl)` это 256 — не срабатывать, стать 256-Δ (счётчик +$20 дайвера
; стартует с нуля: в оригинале клавиатура впервые опрашивается через 255 тиков).
	ld a,(tb_delta)
	cpl
	inc a			; -Δ = 256-Δ
	ld (hl),a
	scf			; C — ещё не досчитал
	ret
tb_dec1:
	ld a,(tb_delta)
	cpl			; ~Δ = -Δ-1
	add a,(hl)		; t-Δ-1; перенос <=> t >= Δ+1
	inc a			; t-Δ (перенос цел)
	ld (hl),a
	ret c			; ещё не досчитал
	cpl
	inc a			; перелёт = Δ-t
	ld (tb_over),a
	or a			; NC
	ret
; --- tb_reload: A = период -> (HL) := период - перелёт. A цел. ----------------
tb_reload:
	push bc
	ld b,a
	ld a,(tb_over)
	cpl
	inc a
	add a,b
	ld (hl),a
	ld a,b
	pop bc
	ret

; --- срабатывание в развёртке обхода: A = t-Δ (<= 0), HL -> поле +$0F -----------
; Перезарядка LB737 (+$0F := +$0E) корректируется на перелёт. Бережёт BC, HL.
SCAN_HITC_TB:
	cpl
	inc a
	ld (tb_over),a		; перелёт = Δ - t
	push bc
	push hl
	ld bc,0FFF1h
	add hl,bc
	ld (z80_ix),hl
	CALL LB737
	ld hl,(z80_ix)
	ld bc,000Fh
	add hl,bc
	ld a,(tb_over)
	ld b,a
	ld a,(hl)
	sub b
	ld (hl),a		; период - перелёт
	pop hl
	pop bc
	ret
SCAN_HIT21_TB:
	call SCAN_HITC_TB
	ld de,0015h
	ret
SCAN_HIT26_TB:
	call SCAN_HITC_TB
	ld de,001Ah
	ret
SCAN_HIT28_TB:
	call SCAN_HITC_TB
	ld de,001Ch
	ret
