; ЭКСПЕРИМЕНТАЛЬНЫЙ КОД ПОЛОСНОЙ ПАЛИТРЫ — ЭКСПЕРИМЕНТ ЗАКРЫТ.
;
; Файл включается ТОЛЬКО из splash_starter.asm под IFDEF BANDS. В штатной сборке
; заставки ни одного байта отсюда нет, и это проверяется гейтом: штатный стартер
; обязан быть байт в байт равен стартеру коммита f79785f — последнего, доказанно
; работающего на живом железе. Причина требования: образ, собранный в эпоху этих
; экспериментов, на MiSTer дал испорченные цвета и зависание.
;
; Разбор обоих заходов, почему стенд тут не судья и нетронутый третий след
; (залповая схема svofski, ~/projects/vector06js/testroms/brdtestx.asm) —
; в docs/experiment_B_bands_palette.md. НЕ переоткрывать вслепую.

; --- ДИАГНОСТИЧЕСКИЕ ПОЛОСЫ ПАЛИТРЫ -----------------------------------------
; ЭКСПЕРИМЕНТ ЗАКРЫТ решением владельца: на железе полосная палитра не получилась
; ни с полосами, ни с линейкой; штатная заставка остаётся 16-цветной. Разбор двух
; заходов, почему стенд тут не судья и нетронутый след (залповая схема svofski,
; ~/projects/vector06js/testroms/brdtestx.asm) — в docs/experiment_B_bands_palette.md.
; Код оставлен ОТДЕЛЬНОЙ сборочной целью (BANDS=1 / RULER=1): без этих ключей ни
; одного байта отсюда в заставку не попадает, приёмочный набор его не касается.
; НЕ переоткрывать вслепую: сначала прочесть документ.
; Проверка МЕХАНИЗМА, не арта: каждая граница перекрашивает ОДИН слот в явный
; контрастный цвет, чтобы на железе было видно с одного взгляда — полосы есть или
; нет, границы стоят или дышат, лесенка там, где обещана.
;
; Как пишется слот: на MiSTer палитра защёлкивается по цвету, который луч
; показывает В МОМЕНТ out (0x0C). В бордюре луч показывает цвет каймы, поэтому
; кайму на миг перекрашиваем в индекс нужного слота, пишем значение и возвращаем
; кайму назад. ПОБОЧНЫЙ ЭФФЕКТ, ожидаемый: по левому и правому краю экрана будет
; цветная рябь шириной в несколько пикселей — это не дефект, это цена приёма.
;
; Отсчёт строк — циклами: растрового регистра у Вектора нет. Строка = 192 такта
; (кадр 59904 / 312 строк).
;
; Таблица, 4 байта на границу: счёт ожидания, слот, значение, МЕТКА КАЙМЫ.
; Метка — индекс палитры, который кайма показывает мгновение после защёлки: по
; фото экрана видно, где именно легла граница, даже если полоса ушла за кромку.
; Числа в первой колонке — СЧЁТ ИТЕРАЦИЙ ожидания, а не растровые строки: одна
; итерация чуть короче строки (замер: 176 строк набегает за 180 итераций), поэтому
; цели скомпенсированы, чтобы границы легли на 40/76/112/148/184/220.
	IFDEF RULER
; ЛИНЕЙКА: 8 границ РОВНО через 32 счётные строки, слот 1 красится очередным
; цветом радуги. Шаг намеренно равномерный и без компенсации набега — по одному
; фото с железа снимаются сразу три величины: сколько границ попало в видимую
; зону (период счётной строки), где стоит первая (фаза прерывания) и одинаковы ли
; расстояния между полосами (набег округления).
; Все восемь счётов помещаются в байт и лежат ВНУТРИ картинки (она занимает
; растровые строки 40..295). Первая версия ставила восьмую границу на счёт 256,
; и та срабатывала лишь по завороту 8-битного счётчика — случайность, на которую
; опираться нельзя.
bands:
	defb  44, 1, 007h, 2	; красный
	defb  76, 1, 01Fh, 3	; оранжевый
	defb 108, 1, 03Fh, 4	; жёлтый
	defb 140, 1, 038h, 5	; зелёный
	defb 172, 1, 0F8h, 6	; голубой
	defb 204, 1, 0C0h, 7	; синий
	defb 236, 1, 0C7h, 8	; пурпурный
	defb 254, 1, 0FFh, 9	; белый
	defb 0FFh
	ELSE
bands:
	defb  40, 1, 007h, 2	; красный
	defb  77, 1, 038h, 3	; зелёный
	defb 114, 1, 03Fh, 4	; жёлтый
	defb 150, 1, 0FFh, 5	; белый
	defb 187, 1, 0F8h, 6	; голубой
	defb 224, 1, 0C7h, 7	; пурпурный
	defb 0FFh
	ENDIF

bands_run:
	ld hl,bands
	ld c,0			; счётчик строк от входа в прерывание
b_next:
	ld a,(hl)
	cp 0FFh
	jp z,b_done
b_wait:
	ld a,(hl)
	cp c
	jp z,b_hit
	call line_wait
	inc c
	jp b_wait
b_hit:
	inc hl
	ld a,(hl)		; индекс слота
	inc hl
	ld e,(hl)		; значение
	inc hl
	ld d,(hl)		; метка каймы
	inc hl
	out (2),a		; кайма := индекс слота, чтобы защёлка попала в него
	ld a,e
; ОКНО ПОПАДАНИЯ. Защёлка срабатывает, только пока луч показывает кайму, а это
; ~64 такта на строку. Период счётной строки на железе оказался НЕ равен 192
; тактам стенда: набег выводит момент записи из окна (владелец на MiSTer: границы
; 1,2,3 и 5 легли, 4 и 6 промахнулись). Одиночная запись слишком узка.
; Поэтому пишем ПАЧКОЙ, как страховался авторский SetPalette (там 8 повторов):
; пачка шире окна, и дрейф её уже не выбивает.
; ОГОВОРКА, которую надо помнить: если пачка выйдет за кайму в картинку, луч
; покажет уже цвет картинки и очередной out защёлкнет ЧУЖОЙ слот. Поэтому длина
; пачки — параметр сборки (PAL_REPS), а не константа: подбирается по железу.
	REPT PAL_REPS
	out (0x0C),a		; собственно запись слота
	ENDR
	ld a,d
	out (2),a		; метка: кайма мигает своим индексом — видно на фото
	ld a,d			; несколько тактов, чтобы метка была шире пары пикселей
	ld a,d
	ld a,(BorderCol)
	out (2),a		; кайма назад
	inc c
	jp b_next
b_done:
	ret

; Пауза длиной в одну растровую строку минус накладные расходы цикла b_wait.
; Подобрано замером на стенде (такты CPU стенд моделирует точно; неточен он
; только в защёлке палитры — см. риск-лист).
line_wait:
	ld a,LINE_ITER
lw:
	dec a
	jp nz,lw
	ret

BorderCol:	defb 1
