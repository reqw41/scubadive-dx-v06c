; splash_starter.asm — заставка Scuba Dive: картинка + марш Men of Harlech,
; потом штатный старт игры. Архитектурный донор — KV, ветка cas-version
; (src/cas/splash_starter.asm): ППА 0x88, палитра В ГАШЕНИИ, первое прерывание
; холостое, возврат первых трёх байт игры перед прыжком на 0x0100.
;
; Раскладка .rom: [0x0100 jp splash + образ игры][0x5500 этот код и ноты]
;                 [0x8000 плоскости заставки — их кладёт в видеопамять сам
;                  загрузчик ядра, распаковывать нечего].
; Игровой образ внутри файла НЕ ИЗМЕНЁН, кроме трёх первых байт, которые
; стартер возвращает на место перед прыжком (гейт сверяет md5 остального).
;
; Звук: три голоса на трёх каналах ВИ53 — в заставке игра не работает, свободны
; все. Управляющее слово в порт 0x08, счётчики 0/1/2 в портах 0x0B/0x0A/0x09.
; Режим 3 (меандр) для ноты, режим 0 для паузы: выход уходит в ноль и молчит.
; ДЕЛИТЕЛЬ 0 В ПОРТ НЕ ВЫДАЁТСЯ НИКОГДА — на MiSTer счётчик с нулём не стартует;
; таблица делителей построена офлайн и нуля не содержит по построению.

	org 0x5500

SPL_STACK	equ 0x7E00
GAME		equ 0x0100

splash:
	di
	ld sp,SPL_STACK
	ld a,0x88		; ППА: порт B выходом (урок железа из KV)
	out (0),a
	ld a,0xC3		; RST7 -> jp isr_skip
	ld (0x38),a
	ld hl,isr_skip
	ld (0x39),hl
; голоса: указатель, счётчик кадров, порт счётчика, слово режима 3, слово режима 0
; --- автодетект AY -----------------------------------------------------------
; ШИНА AY (BDIR,BC): 1,1 = задать адрес -> порт 0x15; 1,0 = записать данные ->
; порт 0x14; 0,1 = ПРОЧИТАТЬ данные -> ТОЖЕ порт 0x15. В ядре MiSTer разведено
; именно так (BDIR = io_wr & psg_sel, BC = addr[0], Vector-06C.sv + rtl/ym2149.sv),
; поэтому на ЖЕЛЕЗЕ читать надо с 0x15, а чтение 0x14 отдаёт inactive = 0xFF.
; В vector06js НАОБОРОТ: данные читаются с 0x14, а 0x15 возвращает номер регистра.
; Первая версия пробы была откалибрована по стенду (читала 0x14) и на живом AY
; провалилась — заставка молча уходила на ВИ53. Поэтому читаем ОБА порта:
; совпало хоть где-то — чип отвечает. Тот же вывод записан в KV,
; ~/projects/kvalley-v06c src/v06c/vec_boot.asm (проба AY).
; Узора два (0x55 и 0xAA): одиночный прошёл бы и на шине, запомнившей последний байт.
	xor a
	out (0x15),a		; регистр 0 = период тона A, младший байт, читается как есть
	ld a,0x55
	out (0x14),a
	in a,(0x15)		; штатное чтение AY (BDIR=0, BC=1) — так на железе
	cp 0x55
	jp z,ay_p2
	in a,(0x14)		; запасной путь: так читает vector06js
	cp 0x55
	jp nz,no_ay
ay_p2:
	ld a,0xAA
	out (0x14),a
	in a,(0x15)
	cp 0xAA
	jp z,ay_yes
	in a,(0x14)
	cp 0xAA
	jp nz,no_ay
ay_yes:
	ld a,1
	ld (use_ay),a
	call ay_init
	jp det_done
no_ay:
	xor a
	ld (use_ay),a
det_done:

	ld hl,spl_v0
	ld (v0),hl
	ld hl,spl_v1
	ld (v1),hl
	ld hl,spl_v2
	ld (v2),hl
	xor a
	ld (v0+2),a
	ld (v1+2),a
	ld (v2+2),a
	ld (paldone),a
	ld (ended),a
	ei
spl_loop:
	halt
	call chkkey		; клавиша или кнопка джойстика?
	or a
	jp nz,spl_quit
	ld a,(ended)
	cp 3			; все три голоса доиграли?
	jp c,spl_loop
spl_quit:
	di
	call snd_off
; вернуть игре её первые три байта и стартовать
	ld hl,orig3
	ld de,GAME
	ld a,(hl)
	ld (de),a
	inc hl
	inc de
	ld a,(hl)
	ld (de),a
	inc hl
	inc de
	ld a,(hl)
	ld (de),a
	jp GAME

; --- опрос клавиатуры и джойстика -------------------------------------------
; Возврат: A=0 ничего не нажато. Порт 3 — он же регистр вертикального скролла,
; поэтому после скана его СРАЗУ возвращаем в 0xFF (иначе картинка уедет).
chkkey:
; ППА: порт B надо на ВРЕМЯ СКАНА переключить на ВВОД. При 0x88 (порт B выходом,
; как требует видеорежим) чтение порта 2 возвращает защёлку вывода — ноль, то
; есть «нажато всё сразу», и заставка проскакивала мгновенно. Игра в KEYINT
; делает ровно так же: 0x8A на скан, 0x88 обратно.
	ld a,0x8A
	out (0),a
	xor a
	out (3),a		; выбрать все ряды матрицы
	in a,(2)
	ld b,a
	ld a,0xFF
	out (3),a		; вернуть скролл немедленно
	ld a,0x88
	out (0),a		; порт B обратно на вывод (иначе на железе всплывает mode512)
	ld a,b
	cpl			; активный ноль -> активная единица
	or a
	ret nz
	in a,(0x0E)		; штатный джойстик Вектора
	cpl
	and 0xC0		; только кнопки Fire1/Fire2
	ret

; --- прерывание --------------------------------------------------------------
isr_skip:			; первое прерывание холостое (урок KV)
	ld hl,isr
	ld (0x39),hl
	ei
	ret

isr:
	push af
	push bc
	push de
	push hl
	ld a,0xFF
	out (3),a		; скролл
	ld a,(paldone)
	or a
	jp z,isr_pal		; первый кадр: программируем палитру, полосы пропускаем
	IFDEF BANDS
; ПОЛОСЫ СНАЧАЛА, до музыки: вход в прерывание — единственная фиксированная точка
; кадра, поэтому джиттер границ равен латентности прерывания (длина текущей
; команды, 11..17 тактов — меньше десятой доли строки). Если считать полосы после
; музыки, её плавающая длительность (~1500 тактов на смене ноты) раскачала бы
; границы на ±8 строк.
; Раньше вызов стоял ПОСЛЕ проверки paldone, и переход jp nz перепрыгивал через
; него на всех кадрах кроме первого — полосы срабатывали ровно один раз.
	call bands_run
	ENDIF
	jp isr_snd
isr_pal:
	inc a
	ld (paldone),a
; ПАЛИТРА ПИШЕТСЯ В ГАШЕНИИ: мы здесь сразу после прерывания кадра, то есть в
; вертикальном гасящем ходе — ровно то место, где ядро MiSTer защёлкивает слот
; по выводимому цвету. Вне гашения палитра защёлкивается не туда.
	ld hl,pal+15
	ld de,0x100F
ploop:
	ld a,e
	out (2),a
	ld a,(hl)
	out (0x0C),a
	out (0x0C),a
	out (0x0C),a
	out (0x0C),a
	out (0x0C),a
	dec hl
	out (0x0C),a
	dec e
	out (0x0C),a
	dec d
	out (0x0C),a
	jp nz,ploop
	xor a
	out (2),a
isr_snd:
	ld hl,v0
	call tick
	ld hl,v1
	call tick
	ld hl,v2
	call tick
	pop hl
	pop de
	pop bc
	pop af
	ei
	ret

; --- один шаг голоса ---------------------------------------------------------
; HL -> дескриптор: +0 указатель ноты (2), +2 счётчик кадров, +3 порт счётчика,
;                   +4 слово режима 3, +5 слово режима 0
tick:
	ld (tk_desc),hl
	ld de,2
	add hl,de		; -> счётчик кадров
	ld a,(hl)
	or a
	jp z,tk_next
	dec a
	ld (hl),a
	ret
tk_next:
	ld hl,(tk_desc)
	ld e,(hl)
	inc hl
	ld d,(hl)		; DE = указатель ноты
	ld a,(de)
	inc de
	cp 0xFF
	jp z,tk_end
	ld (tk_note),a
	ld hl,(tk_desc)		; сохранить продвинутый указатель
	ld (hl),e
	inc hl
	ld (hl),d
; длительность: (байт>>5)+1 восьмых, восьмая = 12 кадров
	ld a,(tk_note)
	rlca
	rlca
	rlca
	and 0x07
	inc a
	ld e,a
	xor a
tk_mul:
	add a,12
	dec e
	jp nz,tk_mul
	dec a			; счётчик считает до нуля включительно
	ld hl,(tk_desc)
	ld de,2
	add hl,de
	ld (hl),a		; счётчик кадров
	inc hl
	ld a,(hl)
	ld (tk_port),a
	inc hl
	ld a,(hl)
	ld (tk_m3),a
	inc hl
	ld a,(hl)
	ld (tk_m0),a
	inc hl
	ld a,(hl)
	ld (tk_areg),a		; базовый регистр периода AY (0/2/4)
	inc hl
	ld a,(hl)
	ld (tk_avol),a		; громкость голоса на AY
; высота
	ld a,(tk_note)
	and 0x1F
	cp 31
	jp z,tk_rest
	ld (tk_pitch),a
	ld a,(use_ay)
	or a
	jp nz,tk_note_ay
; --- нота на ВИ53 ---
	ld a,(tk_pitch)
	ld l,a
	ld h,0
	add hl,hl		; индекс * 2
	ld de,spl_div
	add hl,de
	ld a,(tk_m3)
	out (8),a		; режим 3 (меандр) для своего канала
	ld a,(hl)
	call outc		; младший байт делителя
	inc hl
	ld a,(hl)
	call outc		; старший
	ret
; --- нота на AY: два регистра периода своего канала ---
tk_note_ay:
	ld a,(tk_pitch)
	ld l,a
	ld h,0
	add hl,hl
	ld de,spl_ay
	add hl,de
	ld a,(tk_areg)		; тонкий период канала
	ld c,(hl)
	call ay_wr
	inc hl
	ld a,(tk_areg)
	inc a			; грубый период
	ld c,(hl)
	call ay_wr
	ld a,(tk_areg)
	rrca			; регистр громкости: 0->8, 2->9, 4->10
	add a,8
	ld hl,tk_avol
	ld c,(hl)
	call ay_wr		; вернуть громкость голоса (после паузы она была 0)
	ret
tk_rest:
	ld a,(use_ay)
	or a
	jp nz,tk_rest_ay
	ld a,(tk_m0)
	out (8),a		; режим 0 — выход в ноль, канал молчит
	xor a
	call outc
	xor a
	call outc
	ret
tk_rest_ay:
	ld a,(tk_areg)
	rrca
	add a,8			; регистр громкости своего канала
	ld c,0			; тишина
	call ay_wr
	ret
tk_end:
	ld hl,(tk_desc)
	ld de,3
	add hl,de
	ld a,(hl)
	ld (tk_port),a
	inc hl
	inc hl
	ld a,(hl)
	ld (tk_m0),a
	inc hl
	ld a,(hl)
	ld (tk_areg),a
	ld a,(use_ay)
	or a
	jp nz,tk_end_ay
	ld a,(tk_m0)
	out (8),a		; режим 0 — канал молчит
	xor a
	call outc
	xor a
	call outc
	jp tk_end_done
tk_end_ay:
	ld a,(tk_areg)
	rrca
	add a,8
	ld c,0			; громкость 0
	call ay_wr
tk_end_done:
	ld hl,ended
	inc (hl)
	ret

; Вывод A в порт, номер которого в ячейке tk_port. На i8080 команды out (c),a
; нет, поэтому номер порта подставляется самомодификацией.
outc:
	ld (outc_v+1),a
	ld a,(tk_port)
	ld (outc_i+1),a
outc_v:
	ld a,0
outc_i:
	out (0),a
	ret

tk_desc:	defw 0
tk_note:	defb 0
tk_port:	defb 0
tk_m3:		defb 0
tk_m0:		defb 0
tk_pitch:	defb 0
tk_areg:	defb 0
tk_avol:	defb 0
use_ay:		defb 0


; --- AY -----------------------------------------------------------------------
; Запись регистра: A = номер, C = значение.
ay_wr:
	out (0x15),a		; номер регистра
	ld a,c
	out (0x14),a		; значение
	ret

; Тоны на трёх каналах, шум выключен; громкости фиксированные: мелодия громче,
; бас и гармония тише (раз уж AY умеет громкость — используем её).
ay_init:
	ld a,7
	ld c,0x38		; биты 0-2 тон разрешён (ноль), биты 3-5 шум запрещён
	call ay_wr
	ld a,8
	ld c,13			; канал A — мелодия
	call ay_wr
	ld a,9
	ld c,10			; канал B — бас
	call ay_wr
	ld a,10
	ld c,9			; канал C — гармония
	call ay_wr
	ret

; Выключить все три канала: режим 0 с нулевым счётом — выход уходит в ноль и
; там остаётся. Нулевой ДЕЛИТЕЛЬ в режиме 3 не выдаётся никогда (на MiSTer такой
; счётчик не стартует), а в режиме 0 это штатная тишина.
snd_off:
	ld a,(use_ay)
	or a
	jp z,snd_off_vi
	ld a,8
	ld c,0
	call ay_wr
	ld a,9
	ld c,0
	call ay_wr
	ld a,10
	ld c,0
	call ay_wr
	ret
snd_off_vi:
	ld a,0x30
	out (8),a
	xor a
	out (0x0B),a
	out (0x0B),a
	ld a,0x70
	out (8),a
	xor a
	out (0x0A),a
	out (0x0A),a
	ld a,0xB0
	out (8),a
	xor a
	out (9),a
	out (9),a
	ret


	IFDEF BANDS
; --- ДИАГНОСТИЧЕСКИЕ ПОЛОСЫ ПАЛИТРЫ -----------------------------------------
; ЭКСПЕРИМЕНТ ЗАКРЫТ решением владельца: на железе полосная палитра не получилась
; ни с полосами, ни с линейкой; штатная заставка остаётся 16-цветной. Разбор двух
; заходов, почему стенд тут не судья и нетронутый след (залповая схема svofski,
; ~/projects/vector06js/testroms/brdtestx.asm) — в docs/experiment_B_bands_palette.md.
; Код оставлен ОТДЕЛЬНОЙ сборочной целью (BANDS=1 / RULER=1): без этих ключей ни
; одного байта отсюда в заставку не попадает, приёмочный набор его не касается.
; НЕ переоткрывать вслепую: сначала прочесть документ.
; Проверка МЕХАНИЗМА, не арта: каждая граница перекрашивает ОДИН слот в явный
; контрастный цвет, чтобы на железе было видно с одного взгляда — полосы есть или
; нет, границы стоят или дышат, лесенка там, где обещана.
;
; Как пишется слот: на MiSTer палитра защёлкивается по цвету, который луч
; показывает В МОМЕНТ out (0x0C). В бордюре луч показывает цвет каймы, поэтому
; кайму на миг перекрашиваем в индекс нужного слота, пишем значение и возвращаем
; кайму назад. ПОБОЧНЫЙ ЭФФЕКТ, ожидаемый: по левому и правому краю экрана будет
; цветная рябь шириной в несколько пикселей — это не дефект, это цена приёма.
;
; Отсчёт строк — циклами: растрового регистра у Вектора нет. Строка = 192 такта
; (кадр 59904 / 312 строк).
;
; Таблица, 4 байта на границу: счёт ожидания, слот, значение, МЕТКА КАЙМЫ.
; Метка — индекс палитры, который кайма показывает мгновение после защёлки: по
; фото экрана видно, где именно легла граница, даже если полоса ушла за кромку.
; Числа в первой колонке — СЧЁТ ИТЕРАЦИЙ ожидания, а не растровые строки: одна
; итерация чуть короче строки (замер: 176 строк набегает за 180 итераций), поэтому
; цели скомпенсированы, чтобы границы легли на 40/76/112/148/184/220.
	IFDEF RULER
; ЛИНЕЙКА: 8 границ РОВНО через 32 счётные строки, слот 1 красится очередным
; цветом радуги. Шаг намеренно равномерный и без компенсации набега — по одному
; фото с железа снимаются сразу три величины: сколько границ попало в видимую
; зону (период счётной строки), где стоит первая (фаза прерывания) и одинаковы ли
; расстояния между полосами (набег округления).
; Все восемь счётов помещаются в байт и лежат ВНУТРИ картинки (она занимает
; растровые строки 40..295). Первая версия ставила восьмую границу на счёт 256,
; и та срабатывала лишь по завороту 8-битного счётчика — случайность, на которую
; опираться нельзя.
bands:
	defb  44, 1, 007h, 2	; красный
	defb  76, 1, 01Fh, 3	; оранжевый
	defb 108, 1, 03Fh, 4	; жёлтый
	defb 140, 1, 038h, 5	; зелёный
	defb 172, 1, 0F8h, 6	; голубой
	defb 204, 1, 0C0h, 7	; синий
	defb 236, 1, 0C7h, 8	; пурпурный
	defb 254, 1, 0FFh, 9	; белый
	defb 0FFh
	ELSE
bands:
	defb  40, 1, 007h, 2	; красный
	defb  77, 1, 038h, 3	; зелёный
	defb 114, 1, 03Fh, 4	; жёлтый
	defb 150, 1, 0FFh, 5	; белый
	defb 187, 1, 0F8h, 6	; голубой
	defb 224, 1, 0C7h, 7	; пурпурный
	defb 0FFh
	ENDIF

bands_run:
	ld hl,bands
	ld c,0			; счётчик строк от входа в прерывание
b_next:
	ld a,(hl)
	cp 0FFh
	jp z,b_done
b_wait:
	ld a,(hl)
	cp c
	jp z,b_hit
	call line_wait
	inc c
	jp b_wait
b_hit:
	inc hl
	ld a,(hl)		; индекс слота
	inc hl
	ld e,(hl)		; значение
	inc hl
	ld d,(hl)		; метка каймы
	inc hl
	out (2),a		; кайма := индекс слота, чтобы защёлка попала в него
	ld a,e
; ОКНО ПОПАДАНИЯ. Защёлка срабатывает, только пока луч показывает кайму, а это
; ~64 такта на строку. Период счётной строки на железе оказался НЕ равен 192
; тактам стенда: набег выводит момент записи из окна (владелец на MiSTer: границы
; 1,2,3 и 5 легли, 4 и 6 промахнулись). Одиночная запись слишком узка.
; Поэтому пишем ПАЧКОЙ, как страховался авторский SetPalette (там 8 повторов):
; пачка шире окна, и дрейф её уже не выбивает.
; ОГОВОРКА, которую надо помнить: если пачка выйдет за кайму в картинку, луч
; покажет уже цвет картинки и очередной out защёлкнет ЧУЖОЙ слот. Поэтому длина
; пачки — параметр сборки (PAL_REPS), а не константа: подбирается по железу.
	REPT PAL_REPS
	out (0x0C),a		; собственно запись слота
	ENDR
	ld a,d
	out (2),a		; метка: кайма мигает своим индексом — видно на фото
	ld a,d			; несколько тактов, чтобы метка была шире пары пикселей
	ld a,d
	ld a,(BorderCol)
	out (2),a		; кайма назад
	inc c
	jp b_next
b_done:
	ret

; Пауза длиной в одну растровую строку минус накладные расходы цикла b_wait.
; Подобрано замером на стенде (такты CPU стенд моделирует точно; неточен он
; только в защёлке палитры — см. риск-лист).
line_wait:
	ld a,LINE_ITER
lw:
	dec a
	jp nz,lw
	ret

BorderCol:	defb 1
	ENDIF

